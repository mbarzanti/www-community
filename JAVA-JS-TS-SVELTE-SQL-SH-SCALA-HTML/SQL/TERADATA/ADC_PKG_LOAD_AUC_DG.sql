                    CLOSE SESSION_ENQUEUERS_CUR;
                END;
                COMMIT;
                raise_application_error(-20001,'SUPERATO IL NUMERO MASSIMO DI JOB DI ACCODADAMENTO PARALLELI: ' || ACTUAL_JOB_COUNT );
            END IF;

			ELSE

				LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - VIRTUAL QUEUE ' || V_VIRTUAL_QUEUE || ' DISABLED: CLEAR ' || TABLE_NAME, ADC_PKG_COMMON.ERROR_LEVEL,INPUT_ID_SESSION);

				FOR ITEM IN(
					SELECT J.FLUSSO_ID  FROM ADC_TX_JOBID_SESSION J WHERE J.SESSION_ID = INPUT_ID_SESSION AND J.VIRTUAL_QUEUE= V_VIRTUAL_QUEUE) LOOP
					BEGIN
					LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - DROP ' || TABLE_NAME || ' PARTITION ' || ITEM.FLUSSO_ID, ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION);  
						EXECUTE IMMEDIATE 'ALTER TABLE ' || TABLE_NAME || ' DROP PARTITION FOR (' || ITEM.FLUSSO_ID || ') UPDATE GLOBAL INDEXES';
					EXCEPTION WHEN OTHERS THEN
						LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - ERROR IN DROP ' || TABLE_NAME || ' PARTITION ' || ITEM.FLUSSO_ID, ADC_PKG_COMMON.ERROR_LEVEL, INPUT_ID_SESSION);  
					END;
				END LOOP;
				/* -- SOSTITURE CON L'INVOCAZIONE STARTUP PROCEDURE CON L'AGGIUNTA DELLO STATO
				DELETE FROM ADC_TX_JOBID_SESSION_BIC_EXP 
                        WHERE
                        STATO = STATO_READY AND
                        VIRTUAL_QUEUE= V_VIRTUAL_QUEUE AND SESSION_ID = INPUT_ID_SESSION ;  */

				raise_application_error (-20001,'CODA VIRTUALE ' || V_VIRTUAL_QUEUE || ' DISABILITATA');
			END IF;

			LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||')- END ', ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION);  
    END;

