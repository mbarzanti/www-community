                        and  (V_ULTIMA_MODIFICA_CONTATTI < JMSTIMESTAMP)) THEN
                            creaContattiMessage := true;
                            logResult := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA -  SEZIONE CONTATTI CLIENTE VARIATA ', ADC_PKG_COMMON.DEBUG_LEVEL,TID);
                    END IF;

                    /* controllo variazione degli indirizzi*/

                    IF (MESSAGE.existsNode('.//cmf:indirizzi/cmf:isChangedFLAG', ns)=1 and MESSAGE.extract('.//cmf:indirizzi/cmf:isChangedFLAG/node()', ns).getStringVal()= '1' 
