    PROCEDURE EXPORT_ANAGRAFICA_UNICA (cliente varchar2, idAnagraficaBase number, idClienteBic number, cf varchar2, piva varchar2, dsTimestamp timestamp, TID VARCHAR2, JOB_ID VARCHAR2) IS

    request XMLType;
    doc xmldom.DOMDocument; 
    main_node xmldom.DOMNode;
    root_node xmldom.DOMNode;
    root_elmt xmldom.DOMElement;
    v_max_retries number;

    id pls_integer;
    message sys.aq$_jms_bytes_message;
    MESSAGE_TO_WRITE blob;
    enqueue_options    dbms_aq.enqueue_options_t;
    message_properties dbms_aq.message_properties_t;
    msgid raw(16);
    IN_QUEUE VARCHAR(100);

    LOGRESULT                       NUMBER;
    L_START                         NUMBER;
    L_END                           NUMBER;

    BEGIN

        LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '[' || idClienteBic || '] EXPORT_ANAGRAFICA_UNICA (JOB ID: ' || JOB_ID || ' ) - BEGIN '  ,ADC_PKG_COMMON.INFO_LEVEL,TID);  
        L_START := DBMS_UTILITY.GET_TIME ;  -- Start Time

        IN_QUEUE := 'Q_EXPORT_AUC';

        BEGIN
            select max_retries into v_max_retries from user_queues where name = IN_QUEUE;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            v_max_retries := 2;
        END;
        message := sys.aq$_jms_bytes_message.construct;
        id := message.clear_body(-1);

        doc := xmldom.newDOMDocument;
        main_node := xmldom.makeNode(doc);
        root_elmt := xmldom.createElement(
            doc
          ,   'exportAnagraficaDG'
        );
        xmldom.setAttribute(root_elmt, 'xmlns', 'http://ws.adc.poste.it/ADC/xsd/anagraficaUnica');
        root_node := xmldom.appendChild(
            main_node
          , xmldom.makeNode(root_elmt)
        );

        ADC_PKG_USAGE.createtextnode(Doc,cliente,'cliente',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,idAnagraficaBase,'CodClienteSorgente',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,'PCL','CodSistemaSorgente',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,'I','TipoElaborazione',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,idClienteBic,'IdClienteBic',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,TID,'TID',root_node);        
        ADC_PKG_USAGE.createtextnode(Doc,cf,'cf',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,piva,'piva',root_node);
        ADC_PKG_USAGE.createtextnode(Doc, TO_CHAR(dsTimestamp, 'yyyy-MM-dd HH24:MI:SS'),'dsTimestamp',root_node);
        ADC_PKG_USAGE.createtextnode(Doc,v_max_retries ,'maxRetry',root_node);
        request := xmldom.getXMLType(doc);
        xmldom.freeDocument(doc);

        MESSAGE_TO_WRITE := request.getBlobVal(nls_charset_id('UTF8'));

        message.write_bytes(ID,MESSAGE_TO_WRITE);
        message.flush(id);
        sys.aq$_jms_bytes_message.clean_all();

        BEGIN
            dbms_aq.enqueue(queue_name => IN_QUEUE,
                        enqueue_options => enqueue_options,
                        message_properties => message_properties,
                        payload => message,
                        msgid => msgid);
             COMMIT;
        EXCEPTION WHEN OTHERS THEN
           LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '[' || idClienteBic || '] EXPORT_ANAGRAFICA_UNICA (JOB ID: ' || JOB_ID || ' ) - ERROR ENQUEUING MESSAGE', ADC_PKG_COMMON.ERROR_LEVEL, TID);  
        END;

        L_END := DBMS_UTILITY.GET_TIME ;  -- End Time

        LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '[' || idClienteBic || '] EXPORT_ANAGRAFICA_UNICA (JOB ID: ' || JOB_ID || ' ) - END - ENQUEUED MESSAGES '||msgid||' INTO ' || IN_QUEUE  || '(elapsed:'|| (L_END - L_START)/100 ||' s)', ADC_PKG_COMMON.INFO_LEVEL, TID);  


    END;

