            creaClienteBusinessMessage := false;
            creaContattiMessage := false;
            creaIndirizziMessage := false;
            creaFigureCorrelateMessage := false;

            idAnagraficaBase := null;
            idClienteAuc := null;

            clienteBusinessNode := null;
            clienteRetailNode := null;
            listaIndirizziNode := null;
            listaContattiNode:= null;
            listaFigureCorrelateNode := null;

            V_CLIENTI_B_MESSAGE_BODY := null;
            V_CLIENTI_R_MESSAGE_BODY := null;
            V_CONTATTI_MESSAGE_BODY  := null;
            V_INDIRIZZI_MESSAGE_BODY := null;
            V_FIGURE_CORR_MESSAGE_BODY := null; 
