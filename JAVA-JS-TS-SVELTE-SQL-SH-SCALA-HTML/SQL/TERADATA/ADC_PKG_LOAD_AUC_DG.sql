                                        IS_DEBUG_ENABLED => IS_DEBUG_ENABLED,
                                        TID => TID,
                                        JOB_ID => JOB_ID,
                                        ID_CLIENTE_AUC => V_ID_CLIENTE_AUC,
                                        ID_ANAGRAFICA_BASE => V_ID_ANAGRAFICA_BASE,
                                        CLIENTI_BUSINESS_MSG => V_CLIENTE_BUSINESS_MESSAGE);
                    END IF;

                    IF (V_ID_ANAGRAFICA_BASE IS NOT NULL)  THEN

                        IF(V_INDIRIZZI_MESSAGE IS NOT NULL)THEN
                                MANAGE_INDIRIZZI(    
                                            IS_DEBUG_ENABLED => IS_DEBUG_ENABLED,
                                            JOB_ID => JOB_ID,
                                            TID => TID,
                                            ID_CLIENTE_AUC => V_ID_CLIENTE_AUC,
                                            ID_ANAGRAFICA_BASE => V_ID_ANAGRAFICA_BASE,
                                            TIPO_CLIENTE_FONTE => V_TIPO_CLIENTE_FONTE,
                                            INDIRIZZI => V_INDIRIZZI_MESSAGE);

                        END IF;

                        IF(V_FIGURE_CORRELATE_MESSAGE IS NOT NULL)THEN

                                MANAGE_FIGURE_CORRELATE(    
                                            IS_DEBUG_ENABLED => IS_DEBUG_ENABLED,
                                            JOB_ID => JOB_ID,
                                            TID => TID,
                                            ID_CLIENTE_AUC => V_ID_CLIENTE_AUC,
                                            ID_ANAGRAFICA_BASE => V_ID_ANAGRAFICA_BASE,
                                            FIGURE_CORRELATE => V_FIGURE_CORRELATE_MESSAGE);

                        END IF;

                        IF(V_CONTATTI_MESSAGE IS NOT NULL)THEN

                                MANAGE_CONTATTI(            
                                            IS_DEBUG_ENABLED => IS_DEBUG_ENABLED,
                                            TID => TID,
                                            JOB_ID => JOB_ID,
                                            ID_ANAGRAFICA_BASE => V_ID_ANAGRAFICA_BASE,
