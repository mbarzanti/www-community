                    END IF;

                    IF (MESSAGE.existsNode('.//cmf:clienteRetail/cmf:isChangedFLAG', ns)=1 and MESSAGE.extract('.//cmf:clienteRetail/cmf:isChangedFLAG/node()', ns).getStringVal()= '1' 
                        and  (V_ULTIMA_MODIFICA_CLIENTE < JMSTIMESTAMP)) THEN
                        creaClienteRetailMessage := true;
