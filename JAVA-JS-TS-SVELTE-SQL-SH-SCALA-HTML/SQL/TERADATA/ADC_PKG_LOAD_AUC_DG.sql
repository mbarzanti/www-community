    PROCEDURE INSERIMENTO_FIGURE_CORRELATE(
                            IS_DEBUG_ENABLED  BOOLEAN,
                            TID VARCHAR2,
                            JOB_ID NUMBER,
                            ID_ANAGRAFICA_BASE NUMBER,
                            ID_CLIENTE_AUC VARCHAR2,
                            FIG_CORRELATE AUC_DG_FIGURE_CORR_MSG_TA
    ) AS

          LOGRESULT    NUMBER;

          V_TIPO_CLIENTE_FONTE VARCHAR2(10 BYTE);
          V_ID_CLIENTE_AUC_IN NUMBER;
          V_ID_ANAGRAFICA_BASE_IN NUMBER;
          V_FIG_CORRELATE_TABLE AUC_DG_FIGURE_CORR_MSG_TABLE;
          V_ID_ANAGRAFICA_BASE_RETAIL NUMBER;
          V_ID_AUC_RETAIL NUMBER;
          J PLS_INTEGER;

          V_ID_FIG_CORRELATA_LOAD NUMBER;

          rigaFigCorrelata   ADC_CLIENTE_BUSINESS_RETAIL%ROWTYPE;

          --diagnostic variables
          DIAGNOSTIC_CODE VARCHAR2(512):='IFG9003';
          DIAGNOSTIC_LN VARCHAR2(512):=ADC_PKG_LOAD_AUC_DG.DIAGNOSTIC_LOGGER_NAME;
          DIAGNOSTIC_INFO_LEVEL VARCHAR2(512):=ADC_PKG_COMMON.INFO_LEVEL;
          DIAGNOSTIC_RESULT NUMBER;
            motivo_scarto varchar2(32767);
          BEGIN

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_FIGURE_CORRELATE (JOB ID: ' || JOB_ID || ' ) - BEGIN', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);
            V_ID_ANAGRAFICA_BASE_IN := ID_ANAGRAFICA_BASE;
            V_ID_CLIENTE_AUC_IN := ID_CLIENTE_AUC;

            V_FIG_CORRELATE_TABLE := FIG_CORRELATE.FIGURE_CORR_TABLE;

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-B-00020' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            DELETE FROM ADC_CLIENTE_BUSINESS_RETAIL WHERE ID_CLIENTE_BUSINESS=V_ID_ANAGRAFICA_BASE_IN;

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-E-00020' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_FIGURE_CORRELATE (JOB ID: ' || JOB_ID || ' ) - CANCELLATE FIGURE CORRELATE PER ID_CLIENTE_BIC: ' || ID_CLIENTE_AUC || ' E ANAG_BASE: ' || V_ID_ANAGRAFICA_BASE_IN, ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

            J := V_FIG_CORRELATE_TABLE.FIRST;

            WHILE J IS NOT NULL LOOP
            BEGIN          
                V_ID_AUC_RETAIL := V_FIG_CORRELATE_TABLE(J).RIF_BIC_RETAIL;

                BEGIN
                  SELECT R.ID INTO V_ID_ANAGRAFICA_BASE_RETAIL
                  FROM ADC_ANAGRAFICA_BASE R
                  WHERE (R.ID_CLIENTE_BIC = V_ID_AUC_RETAIL ) ORDER BY R.ULTIMA_MODIFICA_BIC desc fetch first 1 rows only;
                EXCEPTION WHEN NO_DATA_FOUND THEN

                  V_ID_ANAGRAFICA_BASE_RETAIL := NULL;
                  LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_FIGURE_CORRELATE (JOB ID: ' || JOB_ID || ' ) - ANAGRAFICA FIGURA CORRELATA CON ID_BIC ' || V_ID_AUC_RETAIL || ' NON CENSITA', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

                END;

                rigaFigCorrelata.DATA_INIZIO_RELAZIONE := V_FIG_CORRELATE_TABLE(J).DATA_INIZIO_RELAZIONE;
                rigaFigCorrelata.DATA_FINE_RELAZIONE := V_FIG_CORRELATE_TABLE(J).DATA_FINE_RELAZIONE;
                rigaFigCorrelata.RIF_BIC_RETAIL := V_FIG_CORRELATE_TABLE(J).RIF_BIC_RETAIL;
                rigaFigCorrelata.ID_TIPO_RELAZIONE := V_FIG_CORRELATE_TABLE(J).ID_TIPO_RELAZIONE;
                rigaFigCorrelata.ID := NULL;
                rigaFigCorrelata.ID_CLIENTE_BUSINESS := V_ID_ANAGRAFICA_BASE_IN;
                rigaFigCorrelata.ID_CLIENTE_RETAIL := V_ID_ANAGRAFICA_BASE_RETAIL;
                rigaFigCorrelata.RIF_BIC_BUSINESS := V_ID_CLIENTE_AUC_IN;

                IF V_FIG_CORRELATE_TABLE(J).DATA_FINE_RELAZIONE < CURRENT_TIMESTAMP THEN
                  rigaFigCorrelata.FLG_CANCELLATO := 1;
                ELSE
                  rigaFigCorrelata.FLG_CANCELLATO := 0;
                END IF;

                rigaFigCorrelata.FLG_CERTIFICATO := NULL;


                V_ID_FIG_CORRELATA_LOAD := INSERTFIGCORRELATA(IS_DEBUG_ENABLED, rigaFigCorrelata, TID);

                J := V_FIG_CORRELATE_TABLE.NEXT(J);

            EXCEPTION WHEN OTHERS THEN
                motivo_scarto := SQLERRM;
                GESTISCI_SCARTI(id_cliente_auc => ID_CLIENTE_AUC, entità => 'FIGURA' , id_elemento => V_FIG_CORRELATE_TABLE(J).ID_TIPO_RELAZIONE, dsTimestamp => V_FIG_CORRELATE_TABLE(J).DS_TIMESTAMP,  tsLavorazione =>CURRENT_TIMESTAMP, motivoScarto => motivo_scarto ,TID =>TID );
                J := V_FIG_CORRELATE_TABLE.NEXT(J);
            END;

            END LOOP;       

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_FIGURE_CORRELATE (JOB ID: ' || JOB_ID || ' ) - END', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

    END;

