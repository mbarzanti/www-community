							I_QUEUEE := I_QUEUEE + 1;

						ELSE

							CURRENT_MIN_ID_CLIENTE_AUC := PARALLEL_TABLE(ROWNUMS(elem)).ID;

						END IF;

                    END LOOP;

                      /* MODIFICARE AGGIUNGENDO EVENTUALMENTE UN PARAMETRO CHE INDICA LO STATO DI ESECUZIONE DEL FLUSSO
                         ES: CREATO CON SUCCESSO
                             NO RECORD
                             ROLLBACK.. ETC..
                      */

                    IF(STARTUP_PROCEDURE IS NOT NULL) THEN
                        /* STARTUP PROCEDURE */
                        PROCEDURE_CALL := 'BEGIN ' || 
                                      STARTUP_PROCEDURE || '( 
                                        INPUT_ID_SESSION             =>  :INPUT_ID_SESSION,
                                        V_VIRTUAL_QUEUE              =>  :INNER_V_VIRTUAL_QUEUE
                                      );
                                  END;
                                  ';                          
