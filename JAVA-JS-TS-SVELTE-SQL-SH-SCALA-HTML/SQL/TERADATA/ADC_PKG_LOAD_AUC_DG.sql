                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:codNazionePiva', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.COD_NAZIONE_PIVA := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:codNazionePiva/text()', ns).getStringVal(); END IF;
