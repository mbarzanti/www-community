                    V_ULTIMA_MODIFICA_CONTATTI := NULL_DATE ;
                    V_ULTIMA_MODIFICA_INDIRIZZI := NULL_DATE ;
                    V_ULTIMA_MODIFICA_FIGURE_CORR := NULL_DATE ;
                END;

                 /* Se il cliente non è censito */

                IF (idAnagraficaBase IS NULL) then
                    logResult := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - CLIENTE NON CENSITO', ADC_PKG_COMMON.DEBUG_LEVEL,TID);

