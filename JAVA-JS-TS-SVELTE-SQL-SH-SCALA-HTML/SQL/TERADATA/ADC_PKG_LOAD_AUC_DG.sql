	PROCEDURE INSERIMENTO_CONTATTI(
                            IS_DEBUG_ENABLED  BOOLEAN,
                            TID VARCHAR2,
                            JOB_ID NUMBER,
                            VIRTUAL_QUEUE VARCHAR2,
                            ID_ANAGRAFICA_BASE NUMBER,
                            TIPO_CLIENTE_FONTE VARCHAR2,
                            CONTATTI AUC_DG_CONTATTI_MSG_TA
        ) AS

        LOGRESULT    NUMBER;

        V_ID_CLIENTE_AUC_IN NUMBER;
        V_ID_ANAGRAFICA_BASE NUMBER;
        V_CONTATTI_TX_TABLE AUC_DG_CONTATTI_MSG_TABLE;
        J PLS_INTEGER;

        V_TIPO_CLIENTE_FONTE VARCHAR2(10 BYTE);

        V_ID_CONTATTO_CLIENTE_LOAD NUMBER;
        TROVATO_PREF NUMBER(2) := 0;
        INDEX_PREF NUMBER := NULL;

        rigaContatti   ADC_CONTATTI_CLIENTE%ROWTYPE;
        rigaContattiScarti ADC_BAD_TX_CONTATTI_DG%ROWTYPE;

        --diagnostic variables
        DIAGNOSTIC_CODE VARCHAR2(512):='IC9005';
        DIAGNOSTIC_LN VARCHAR2(512):=ADC_PKG_LOAD_AUC_DG.DIAGNOSTIC_LOGGER_NAME;
        DIAGNOSTIC_INFO_LEVEL VARCHAR2(512):=ADC_PKG_COMMON.INFO_LEVEL;
        DIAGNOSTIC_RESULT NUMBER;
        IS_BATCH BOOLEAN;
        motivo_scarto varchar2(32767);

        BEGIN

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| CONTATTI.ID_CLIENTE_AUC ||'] INSERIMENTO_CONTATTI (JOB ID: ' || JOB_ID || ' ) - BEGIN', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

            V_ID_CLIENTE_AUC_IN := CONTATTI.ID_CLIENTE_AUC;
            V_CONTATTI_TX_TABLE := CONTATTI.CONTATTI_TX_TABLE;

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-B-00010' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            IF ID_ANAGRAFICA_BASE is NULL THEN --CHIAMATA BATCH
            IS_BATCH := TRUE;
				BEGIN       
                   SELECT R.ID, R.TIPO_CLIENTE_FONTE INTO V_ID_ANAGRAFICA_BASE, V_TIPO_CLIENTE_FONTE
                   FROM ADC_ANAGRAFICA_BASE R
                   WHERE (R.ID_CLIENTE_BIC = V_ID_CLIENTE_AUC_IN ) ORDER BY R.ULTIMA_MODIFICA_BIC desc fetch first 1 rows only;       
                EXCEPTION WHEN NO_DATA_FOUND THEN

                    V_ID_ANAGRAFICA_BASE := NULL;          
                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| CONTATTI.ID_CLIENTE_AUC ||'] INSERIMENTO_CONTATTI (JOB ID: ' || JOB_ID || ' ) - ANAGRAFICA CLIENTE CON ID_BIC ' || V_ID_CLIENTE_AUC_IN || ' NON CENSITA', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);
                    RAISE ANAGRAFICA_MANCANTE;

                END;
            ELSE
            IS_BATCH := FALSE;
                IF  TIPO_CLIENTE_FONTE IS NULL THEN

                    BEGIN 
                       SELECT R.TIPO_CLIENTE_FONTE INTO V_TIPO_CLIENTE_FONTE
                       FROM ADC_ANAGRAFICA_BASE R
                       WHERE (R.ID_CLIENTE_BIC = V_ID_CLIENTE_AUC_IN ) ORDER BY R.ULTIMA_MODIFICA_BIC desc fetch first 1 rows only;       
                    EXCEPTION WHEN NO_DATA_FOUND THEN                    
                        V_TIPO_CLIENTE_FONTE := NULL; 
                    END;
                ELSE 
                    V_TIPO_CLIENTE_FONTE := TIPO_CLIENTE_FONTE;
                END IF;

                V_ID_ANAGRAFICA_BASE:= ID_ANAGRAFICA_BASE;

            END IF;

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-E-00010' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-B-00020' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            DELETE FROM ADC_CONTATTI_CLIENTE WHERE ID_ANAGRAFICA_BASE=V_ID_ANAGRAFICA_BASE;

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-E-00020' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| CONTATTI.ID_CLIENTE_AUC ||'] INSERIMENTO_CONTATTI (JOB ID: ' || JOB_ID || ' ) - CANCELLATI CONTATTI PER ID_CLIENTE_BIC: ' || V_ID_CLIENTE_AUC_IN || ' E ANAG_BASE: ' || V_ID_ANAGRAFICA_BASE, ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

            J := V_CONTATTI_TX_TABLE.FIRST;

            WHILE J IS NOT NULL LOOP
                BEGIN        
                        rigaContatti.ID_TIPO_RIFERIMENTO := V_CONTATTI_TX_TABLE(J).ID_TIPO_RIFERIMENTO;
                        rigaContatti.RIFERIMENTO := V_CONTATTI_TX_TABLE(J).RIFERIMENTO;
                        rigaContatti.DATA_VARIAZIONE := V_CONTATTI_TX_TABLE(J).DS_TIMESTAMP;
                        rigaContatti.ID_ANAGRAFICA_BASE := V_ID_ANAGRAFICA_BASE;
                        rigaContatti.ID := NULL;
                        rigaContatti.PREDEF_LISTE := 'N';
                        rigaContatti.TIPO_CLIENTE_FONTE := V_TIPO_CLIENTE_FONTE;
                        rigaContatti.PREFISSO := V_CONTATTI_TX_TABLE(J).PREFISSO;
                        rigaContatti.ID_PREF_NAZIONE := V_CONTATTI_TX_TABLE(J).ID_PREF_NAZIONE;
                        rigaContatti.DATA_CESSAZIONE := V_CONTATTI_TX_TABLE(J).DT_CESSAZIONE; -- POPOLATO SOLO DALL'ONLINE                     

                        IF (V_CONTATTI_TX_TABLE(J).DT_CESSAZIONE IS NOT NULL) THEN                    
                            rigaContatti.FLG_CANCELLATO := 1;
                        ELSE
                            rigaContatti.FLG_CANCELLATO := 0;
                        END IF;

                        V_ID_CONTATTO_CLIENTE_LOAD := INSERTCONTATTO(IS_DEBUG_ENABLED, rigaContatti, TID);

                        IF rigaContatti.FLG_CANCELLATO = 0 THEN

                            IF rigaContatti.ID_TIPO_RIFERIMENTO = 9 THEN
                               TROVATO_PREF := 10;
                               INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 6) AND (TROVATO_PREF < 10) THEN
                                   TROVATO_PREF := 9;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 30) AND (TROVATO_PREF < 9) THEN
                                   TROVATO_PREF := 8;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 25) AND (TROVATO_PREF < 8) THEN
                                   TROVATO_PREF := 7;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD; 

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 3) AND (TROVATO_PREF < 7) THEN
                                   TROVATO_PREF := 6;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 29) AND (TROVATO_PREF < 6) THEN
                                   TROVATO_PREF := 5;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;

                            --SE SI VUOLE UTILIZZARE UN UNICO CONTROLLO PER RETAIL E BUSINESS 

                            ELSIF (rigaContatti.ID_TIPO_RIFERIMENTO = 5) AND (TROVATO_PREF < 5) THEN
                                   TROVATO_PREF := 4;
                                   INDEX_PREF := V_ID_CONTATTO_CLIENTE_LOAD;					   
                            END IF;
                        END IF;
                     /*GESTIONE EXPORT MESSAGGIO */

                    /*BEGIN

                    /*  INSERT INTO ADC_BIC_TO_EXPORT (ID,ID_FLUSSO,TIPOLOGIA) VALUES (V_ID_CONTATTO_CLIENTE_LOAD, V_CONTATTI_TX_TABLE(J).ID_FLUSSO, VIRTUAL_QUEUE);

                    EXCEPTION
                        WHEN DUP_VAL_ON_INDEX THEN               
