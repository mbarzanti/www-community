                    IF (MESSAGE.existsNode('.//cmf:figureCorrelateBusiness', ns)=1) THEN creaFigureCorrelateMessage := true; END IF;
                    IF (MESSAGE.existsNode('.//cmf:contatti', ns)=1) THEN creaContattiMessage := true; END IF;
