                    END IF;

                    /* controllo variazione figure correlate*/

                    IF (MESSAGE.existsNode('.//cmf:figureCorrelateBusiness/cmf:isChangedFLAG', ns)=1 and MESSAGE.extract('.//cmf:figureCorrelateBusiness/cmf:isChangedFLAG/node()', ns).getStringVal()= '1' 
                        and  (V_ULTIMA_MODIFICA_FIGURE_CORR < JMSTIMESTAMP)) THEN
