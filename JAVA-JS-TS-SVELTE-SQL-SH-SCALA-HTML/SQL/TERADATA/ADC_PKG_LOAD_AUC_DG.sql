                rigaIndirizzi.ID_TIPO_INDIRIZZO := V_INDIRIZZI_TABLE(J).ID_TIPO_RIF_INDIRIZZO;
                rigaIndirizzi.TIPO_STRADA := V_INDIRIZZI_TABLE(J).TIPO_STRADA;
                rigaIndirizzi.NOME_STRADA := V_INDIRIZZI_TABLE(J).NOME_STRADA;
                rigaIndirizzi.CIVICO := V_INDIRIZZI_TABLE(J).NUMERO_CIVICO;
                rigaIndirizzi.CAP := V_INDIRIZZI_TABLE(J).CAP;
                rigaIndirizzi.ID_NAZIONE := V_INDIRIZZI_TABLE(J).COD_NAZIONE_CLI;
                rigaIndirizzi.ID_PROVINCIA := V_INDIRIZZI_TABLE(J).SIGLA_PROVINCIA_CLI;
                rigaIndirizzi.ID_COMUNE := V_INDIRIZZI_TABLE(J).COD_COMUNE_MIN_FIN;
                rigaIndirizzi.PRESSO := V_INDIRIZZI_TABLE(J).PRESSO;
                rigaIndirizzi.FABBRICATO := V_INDIRIZZI_TABLE(J).FABBRICATO; 
                rigaIndirizzi.ALTRO_CIVICO := V_INDIRIZZI_TABLE(J).CIVICOALTRO;
                rigaIndirizzi.FLG_CANCELLATO := 0;
                rigaIndirizzi.FLAG_NORMALIZZAZIONE := V_INDIRIZZI_TABLE(J).FLAG_NORMALIZZAZIONE;
                rigaIndirizzi.FRAZIONE := V_INDIRIZZI_TABLE(J).FRAZIONE;
                rigaIndirizzi.INDIRIZZO_COMPLETO := V_INDIRIZZI_TABLE(J).IND_COMPLETO;
                --rigaIndirizzi.ID_ANAGRAFICA_BASE := V_ID_ANAGRAFICA_BASE;
                rigaIndirizzi.ID_GEOPOST := V_INDIRIZZI_TABLE(J).ID_INDIRIZZO;
                rigaIndirizzi.ID_CIVICO := V_INDIRIZZI_TABLE(J).ID_CIVICO;

