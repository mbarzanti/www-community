    FUNCTION INSERTCLIENTERETAIL(IS_DEBUG_ENABLED  BOOLEAN, rigaClienteRetail ADC_CLIENTE_RETAIL%ROWTYPE, ID_ANAG_BASE NUMBER, TID VARCHAR2 ) RETURN NUMBER IS
		returnValue NUMBER;
		copia ADC_CLIENTE_RETAIL%ROWTYPE;

		l_start       NUMBER;
		l_end         NUMBER;
		l_diff        NUMBER;
		LOGRESULT     NUMBER;
		V_ID_ANAGRAFICA_BASE NUMBER;

		BEGIN

			L_START := DBMS_UTILITY.GET_TIME ;  -- Start Time  

			COPIA := rigaClienteRetail;
			V_ID_ANAGRAFICA_BASE := rigaClienteRetail.ID_ANAGRAFICA_BASE;

			IF(V_ID_ANAGRAFICA_BASE IS NULL) THEN

				SELECT SEQ_ADC_CLIENTE_RETAIL.NEXTVAL INTO RETURNVALUE FROM DUAL;
				  COPIA.ID := returnValue;
				  COPIA.ID_ANAGRAFICA_BASE := ID_ANAG_BASE;

				  LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INSERTCLIENTERETAIL - INSERIMENTO NUOVO CLIENTE RETAIL CON ID_ANAGRAFICA (' ||   COPIA.ID_ANAGRAFICA_BASE || ') BEGIN'  , ADC_PKG_COMMON.DEBUG_LEVEL,TID);

				  INSERT INTO ADC_CLIENTE_RETAIL VALUES copia;

				  l_end := dbms_utility.get_time ;  -- Start Time

				  LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INSERTCLIENTERETAIL - INSERIMENTO NUOVO CLIENTE RETAIL CON ID_ANAGRAFICA (' ||  COPIA.ID_ANAGRAFICA_BASE  || ') END (elapsed:'|| (l_end - l_start)/100 ||' s)'  , ADC_PKG_COMMON.DEBUG_LEVEL,TID);

			ELSE

				LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INSERTCLIENTERETAIL - AGGIORNAMENTO CLIENTE RETAIL CON ID_ANAGRAFICA (' ||   COPIA.ID_ANAGRAFICA_BASE || ') BEGIN'  , ADC_PKG_COMMON.DEBUG_LEVEL,TID);

				BEGIN       
					SELECT CR.ID INTO RETURNVALUE FROM ADC_CLIENTE_RETAIL CR
					WHERE CR.ID_ANAGRAFICA_BASE = V_ID_ANAGRAFICA_BASE AND ROWNUM=1;       
				EXCEPTION WHEN NO_DATA_FOUND THEN

					RETURNVALUE := NULL;
					LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INSERTCLIENTERETAIL - NESSUN CLIENTE RETAIL ASSOCIATO A ID_ANAGRAFICA (' ||   V_ID_ANAGRAFICA_BASE || ') BEGIN'  , ADC_PKG_COMMON.ERROR_LEVEL,TID);
				END;

				IF RETURNVALUE IS NOT NULL THEN

					copia.ID := RETURNVALUE;
					UPDATE ADC_CLIENTE_RETAIL SET ROW = copia WHERE ID = copia.ID;

				END IF;

				l_end := dbms_utility.get_time ;  -- Start Time

				LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INSERTCLIENTERETAIL - AGGIORNAMENTO CLIENTE RETAIL CON ID_ANAGRAFICA (' ||  COPIA.ID_ANAGRAFICA_BASE  || ') END (elapsed:'|| (l_end - l_start)/100 ||' s)'  , ADC_PKG_COMMON.DEBUG_LEVEL,TID);

			END IF;

		RETURN returnValue;
	END;

