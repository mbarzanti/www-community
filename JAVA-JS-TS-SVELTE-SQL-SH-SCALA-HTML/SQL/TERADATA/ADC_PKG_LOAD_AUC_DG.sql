                );

                LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_SCARTI_NAME, 'DEQUEUE_AUC_GOLDEN_RECORD - MESSAGE ' || V_MESSAGE_HANDLE || ' ENQUEUED INTO ERROR QUEUE ' || ERROR_QUEUE, ADC_PKG_COMMON.DEBUG_LEVEL, TID);

               ROLLBACK TO GESTIONE_SINGOLO_GOLDENRECORD;

            END; --SAVEPOINT;

            L_END := DBMS_UTILITY.GET_TIME ;  
            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_GOLDEN_RECORD (JOB ID: ' || JOB_ID || ') - Message (' ||  MSGID || ') gestito correttamente (elapsed:'|| (L_END - L_START)/100 ||' s)'  , ADC_PKG_COMMON.DEBUG_LEVEL,TID,IS_DEBUG_ENABLED);  

            IF(CURRENT_DEQUEUED_MESSAGE > DEQUEUE_BLOCK_SIZE) THEN

                COMMIT;
                CURRENT_DEQUEUED_MESSAGE:=0;
            END IF;

            EXIT WHEN ((L_END - GLOBAL_START)/100 )> V_SCHEDULING_INTERVAL;

      END LOOP;
      COMMIT;
      GLOBAL_END := DBMS_UTILITY.GET_TIME ; 
      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_AUC_GOLDEN_RECORD (JOB ID: ' || JOB_ID || ' ) - END  -  Messages : ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE ||' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)'  , ADC_PKG_COMMON.INFO_LEVEL,'');  
      ---DBMS_OUTPUT.PUT_LINE('PROCEDURE: DEQUEUE_AUC_GOLDEN_RECORD (JOB ID: ' || JOB_ID || ' ) - END - Messages: ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE || ' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)');  

      ADC_PKG_COMMON.FLUSH_LOGGER(DIAGNOSTIC_LN);

      EXCEPTION

      WHEN NO_MESSAGES THEN
        COMMIT;
        BEGIN
            SELECT QUEUE_TABLE INTO QUEUE_TABLE FROM USER_QUEUES WHERE NAME=IN_QUEUE;
            /* ABBASSA IL HWM */
            DBMS_AQADM.PURGE_QUEUE_TABLE(
                QUEUE_TABLE, 
