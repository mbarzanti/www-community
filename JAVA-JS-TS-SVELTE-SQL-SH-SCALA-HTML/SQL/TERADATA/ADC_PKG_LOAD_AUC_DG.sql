                        WHERE
                        STATO = STATO_READY AND
                        VIRTUAL_QUEUE= V_VIRTUAL_QUEUE AND SESSION_ID = INPUT_ID_SESSION ; 
                    */
                END IF;

			ELSE   -- SUPERATO LA SOGLIA DEI JOB DI ACCODAMENTO
                LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - ATTIVITA'' POSTICIPATA: SUPERATO IL NUMERO MASSIMO DI JOB DI ACCODADAMENTO PARALLELI:' || ACTUAL_JOB_COUNT , ADC_PKG_COMMON.ERROR_LEVEL, INPUT_ID_SESSION);  

                BEGIN                                                                                            
                    OPEN SESSION_ENQUEUERS_CUR;
