                            IF(listaContattiNode IS NOT NULL) THEN
                                V_CONTATTI_MESSAGE_BODY :=  createContattiMessage(listaContattiNode, idClienteAuc,TID);                
                                V_ULTIMA_MODIFICA_CONTATTI := JMSTIMESTAMP;
                            END IF;
                        END IF;

                        IF (creaIndirizziMessage) THEN
                            listaIndirizziNode := MESSAGE.extract('.//cmf:indirizzo', ns); 
                            IF(listaIndirizziNode IS NOT NULL) THEN
                                V_INDIRIZZI_MESSAGE_BODY := createIndirizziMessage(listaIndirizziNode, idClienteAuc,TID);
                                V_ULTIMA_MODIFICA_INDIRIZZI := JMSTIMESTAMP;
                            END IF;
                        END IF;

                    EXCEPTION WHEN OTHERS THEN 
                            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - ERRORE NELLA CREAZIONE DEL MESSAGGIO PER CLIENTE NON CENSITO', ADC_PKG_COMMON.ERROR_LEVEL,TID);
                            BAD_MESSAGE := true;
                            ERRMESSAGE :=  sqlerrm;
                    END;

                END IF;

                IF NOT BAD_MESSAGE THEN

                    IF CLIENTE_NOT_TRACE THEN
                        INSERT INTO ADC_AUC_DG_TRACE(ID_CLIENTE_BIC, ULTIMA_MODIFICA_CLIENTE,ULTIMA_MODIFICA_CONTATTI, ULTIMA_MODIFICA_INDIRIZZI, ULTIMA_MODIFICA_FIGURE_CORR ) VALUES (idClienteAuc, V_ULTIMA_MODIFICA_CLIENTE,V_ULTIMA_MODIFICA_CONTATTI, V_ULTIMA_MODIFICA_INDIRIZZI, V_ULTIMA_MODIFICA_FIGURE_CORR);
                    ELSE
                        UPDATE ADC_AUC_DG_TRACE SET
                        ULTIMA_MODIFICA_CLIENTE = V_ULTIMA_MODIFICA_CLIENTE,
                        ULTIMA_MODIFICA_CONTATTI = V_ULTIMA_MODIFICA_CONTATTI,
                        ULTIMA_MODIFICA_INDIRIZZI  = V_ULTIMA_MODIFICA_INDIRIZZI,
                        ULTIMA_MODIFICA_FIGURE_CORR = V_ULTIMA_MODIFICA_FIGURE_CORR
                        WHERE ID_CLIENTE_BIC = idClienteAuc;

                    END IF;

                    V_ANAGRAFICA_UNICA_MSG_BODY                         := AUC_DG_GOLDEN_MESSAGE_T();
                    V_ANAGRAFICA_UNICA_MSG_BODY.ID_CLIENTE_AUC          := idClienteAuc;
                    V_ANAGRAFICA_UNICA_MSG_BODY.ID_ANAGRAFICA_BASE      := idAnagraficaBase;
                    V_ANAGRAFICA_UNICA_MSG_BODY.AUC_DG_CLIENTE_RETAIL      := V_CLIENTI_R_MESSAGE_BODY;
                    V_ANAGRAFICA_UNICA_MSG_BODY.AUC_DG_CLIENTE_BUSINESS    := V_CLIENTI_B_MESSAGE_BODY;
                    V_ANAGRAFICA_UNICA_MSG_BODY.AUC_DG_FIGURE_CORRELATE    := V_FIGURE_CORR_MESSAGE_BODY;
