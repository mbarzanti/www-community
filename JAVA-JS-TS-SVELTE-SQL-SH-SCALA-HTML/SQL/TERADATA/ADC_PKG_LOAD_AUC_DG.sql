                ELSE

                    logResult := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA -  CLIENTE CENSITO ', ADC_PKG_COMMON.DEBUG_LEVEL,TID);

                    /*controllo variazione dell'anagrafica */

                    IF (MESSAGE.existsNode('.//cmf:clienteBusiness/cmf:isChangedFLAG', ns)=1 and MESSAGE.extract('.//cmf:clienteBusiness/cmf:isChangedFLAG/node()', ns).getStringVal()= '1'
                        and  (V_ULTIMA_MODIFICA_CLIENTE < JMSTIMESTAMP)) THEN 
