                        END;
                    END IF;

				ELSE
                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - NESSUN RECORD PER LA SESSION: ' || INPUT_ID_SESSION , ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION);      
