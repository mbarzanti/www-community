                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:dtCessazione', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.DT_CESSAZIONE := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:dtCessazione/text()', ns).getStringVal(); END IF;
                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:flagCertificazione', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.FLAG_CERTIFICAZIONE := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:flagCertificazione/text()', ns).getStringVal(); END IF;
                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:flagCessazione', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.FLAG_CESSAZIONE := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:flagCessazione/text()', ns).getStringVal(); END IF;
                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:idFormaGiuridica', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.ID_FORMA_GIURIDICA := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:idFormaGiuridica/text()', ns).getStringVal(); END IF;
