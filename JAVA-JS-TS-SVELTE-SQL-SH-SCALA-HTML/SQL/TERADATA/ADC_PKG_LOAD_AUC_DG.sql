            );
        EXCEPTION WHEN NO_DATA_FOUND THEN --TODO TICKE APERTO
          LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_AUC_GOLDEN_RECORD (JOB ID: ' || SQLERRM || ' error in purging queue ' || IN_QUEUE, ADC_PKG_COMMON.ERROR_LEVEL,'');
        END;
            GLOBAL_END := DBMS_UTILITY.GET_TIME ;  -- Start Time
            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_AUC_GOLDEN_RECORD (JOB ID: ' || JOB_ID || ') - END (NO MORE MESSAGES) - Messages: ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE || ' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)'  , ADC_PKG_COMMON.INFO_LEVEL,'');
