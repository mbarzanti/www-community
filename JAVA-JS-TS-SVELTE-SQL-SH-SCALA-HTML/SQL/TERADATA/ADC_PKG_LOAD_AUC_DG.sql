                    END;
*/
                J := V_CONTATTI_TX_TABLE.NEXT(J);

                EXCEPTION WHEN OTHERS THEN
                    IF IS_BATCH THEN
                        RAISE;
                    ELSE
                        motivo_scarto :=sqlerrm;
                        GESTISCI_SCARTI(id_cliente_auc => CONTATTI.ID_CLIENTE_AUC , entità => 'CONTATTO' , id_elemento => V_CONTATTI_TX_TABLE(J).ID_TIPO_RIFERIMENTO, dsTimestamp => V_CONTATTI_TX_TABLE(J).DS_TIMESTAMP,  tsLavorazione =>CURRENT_TIMESTAMP, motivoScarto => motivo_scarto ,TID =>TID );
                        J := V_CONTATTI_TX_TABLE.NEXT(J);
                    END IF;
                END;
            END LOOP;

            IF INDEX_PREF IS NOT NULL THEN

                DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-B-00030' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

