              SELECT PARAMETER_VALUE INTO DEQUEUE_BLOCK_SIZE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'DEFAULT' AND AQC.PARAMETER_TYPE='DEQUEUE_BLOCK_SIZE' AND ROWNUM = 1;
              END;

          DEQUEUED_MESSAGE          :=0;
          CURRENT_DEQUEUED_MESSAGE  :=0;

          LOOP
              L_START := DBMS_UTILITY.GET_TIME ;  -- Start Time

              DBMS_AQ.DEQUEUE(
                             queue_name           => IN_QUEUE,
                             dequeue_options      => V_DEQUEUE_OPTIONS,
                             message_properties   => V_MESSAGE_PROPERTIES,
                             PAYLOAD              => V_CONTATTI_MESSAGE_BODY,
                             MSGID                => MSGID); 

