                       WHERE (R.ID_CLIENTE_BIC = ID_CLIENTE_AUC ) ORDER BY R.ULTIMA_MODIFICA_BIC desc fetch first 1 rows only;       
                EXCEPTION WHEN NO_DATA_FOUND THEN                    
                        V_TIPO_CLIENTE_FONTE := NULL; 
                END;
            ELSE 
                V_TIPO_CLIENTE_FONTE := TIPO_CLIENTE_FONTE;
            END IF;

            V_ID_ANAGRAFICA_BASE_IN := ID_ANAGRAFICA_BASE;

            --V_ID_CLIENTE_AUC_IN := ID_CLIENTE_AUC;
            V_INDIRIZZI_TABLE := INDIRIZZI.INDIRIZZI_TX_TABLE;

