                            END IF;

                        EXCEPTION WHEN NO_DATA_FOUND THEN

                            LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) := 1;                                                     

                        END;

                        j := V_CONTATTI_TX_TABLE.NEXT(j);

                    END LOOP;

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - Message (' ||  V_MESSAGE_HANDLE || ') ERROR IN INSERTING CONTATTI: ' || SQLERRM || ' - ' || dbms_utility.format_error_backtrace  , ADC_PKG_COMMON.ERROR_LEVEL,INPUT_ID_FLUSSO);

              END;
                  -- DBMS_OUTPUT.PUT_LINE(ESITOOPERAZIONE);
