                                  V_MSG_PROPERTIES_TABLE.EXTEND();
                                  V_MSG_PROPERTIES_TABLE(V_MSG_PROPERTIES_TABLE.LAST) := V_MESSAGE_PROPERTIES;

                                  V_CONTATTI_MESSAGE_BODY := AUC_DG_CONTATTI_MSG_TA();
                                  V_CONTATTI_MESSAGE_BODY_ITEM_A := AUC_DG_CONTATTI_MSG_TABLE();

                                  LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE  (JOB ID: ' || JOB_ID || ') - ELABORATO CONTATTI ID_CLIENTE_AUC: ' ||V_ID_CLIENTE_AUC_PREC  , ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_SESSION,IS_DEBUG_ENABLED);  


                               END IF;

                            END IF;

                            BEGIN

                              IF LISTA_CONTATTI_DISTINCT(V_CONTATTI_ROW.ID_CLIENTE_AUC || '-' || V_CONTATTI_ROW.ID_TIPO_RIFERIMENTO).ID_CLIENTE_AUC IS NOT NULL THEN 

                                      V_CONTATTI_ROW.SCARTATO := 1;
                                      V_CONTATTI_ROW.MOTIVO_SCARTO := 'CONTATTO DUPLICATO NEI FILE DEL FLUSSO BATCH CORRENTE';

                                      INSERT INTO ADC_BAD_TX_CONTATTI_DG VALUES V_CONTATTI_ROW;

                                      BAD_MESSAGE_COUNT := BAD_MESSAGE_COUNT + 1;
                                      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE (JOB ID: ' || JOB_ID || ') - BAD RECORD ADDED INTO ADC_BAD_TX_CONTATTI_DG', ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_SESSION,IS_DEBUG_ENABLED);             

                              END IF;

                            EXCEPTION WHEN NO_DATA_FOUND THEN

                                LISTA_CONTATTI_DISTINCT(V_CONTATTI_ROW.ID_CLIENTE_AUC || '-' || V_CONTATTI_ROW.ID_TIPO_RIFERIMENTO) := V_CONTATTI_ROW;
                                V_CONTATTI_MESSAGE_BODY_ITEM_A.EXTEND();
                                V_CONTATTI_MESSAGE_BODY_ITEM_A(V_CONTATTI_MESSAGE_BODY_ITEM_A.LAST) := V_CONTATTI_MESSAGE_BODY_ITEM;

                                LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE  (JOB ID: ' || JOB_ID || ') - ELABORATO ID_CLIENTE_AUC - CONTATTO :' || V_CONTATTI_ROW.ID_CLIENTE_AUC || '-' || V_CONTATTI_ROW.ID_TIPO_RIFERIMENTO, ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_SESSION,IS_DEBUG_ENABLED);  

                                BEGIN

                                  IF LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_MESSAGE_BODY_ITEM.ID_FLUSSO) IS NOT NULL THEN                                             
                                        V_N_MESSAGGI_RIMANENTI := LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_MESSAGE_BODY_ITEM.ID_FLUSSO) + 1;
                                        LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_MESSAGE_BODY_ITEM.ID_FLUSSO) := V_N_MESSAGGI_RIMANENTI;
                                  END IF;

                                EXCEPTION WHEN NO_DATA_FOUND THEN

                                    LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_MESSAGE_BODY_ITEM.ID_FLUSSO) := 1;                                                     

                                END; 

                            END;

                            V_ID_CLIENTE_AUC_PREC := V_CONTATTI_MESSAGE_BODY_ITEM.ID_CLIENTE_AUC;

                    END IF;   

                    DELETE FROM ADC_TX_CONTATTI_DG WHERE ID = V_CONTATTI_ROW.ID AND ID_FLUSSO = V_CONTATTI_ROW.ID_FLUSSO;

                    ADC_PKG_AQ_FRAMEWORK.MARK_AS_NOT_PURGEABLE(IN_QUEUE);

                    END LOOP;

                    IF V_CONTATTI_TX.COUNT < BLOCK_SIZE THEN

                      V_CONTATTI_MESSAGE_BODY.RETRY_COUNT := 0;
                      V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC := V_ID_CLIENTE_AUC_PREC;
                      V_CONTATTI_MESSAGE_BODY.CONTATTI_TX_TABLE := V_CONTATTI_MESSAGE_BODY_ITEM_A;
                      V_CONTATTI_MESSAGE_BODY_ARRAY.EXTEND();
                      V_CONTATTI_MESSAGE_BODY_ARRAY(V_CONTATTI_MESSAGE_BODY_ARRAY.LAST) := V_CONTATTI_MESSAGE_BODY;

                      V_MESSAGE_PROPERTIES.USER_PROPERTY := SYS.ANYDATA.CONVERTNUMBER(V_ID_CLIENTE_AUC_PREC);
                      V_MSG_PROPERTIES_TABLE.EXTEND();
                      V_MSG_PROPERTIES_TABLE(V_MSG_PROPERTIES_TABLE.LAST) := V_MESSAGE_PROPERTIES;

                    END IF;

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE  (JOB ID: ' || JOB_ID || ') - ELABORATO CONTATTI ID_CLIENTE_AUC: ' ||V_ID_CLIENTE_AUC_PREC  , ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_SESSION,IS_DEBUG_ENABLED);  


                    Q_START := DBMS_UTILITY.GET_TIME;

                    if(V_CONTATTI_MESSAGE_BODY_ARRAY.COUNT > 0) THEN

                          v_enqueued_cnt := DBMS_AQ.ENQUEUE_ARRAY(
                                                    QUEUE_NAME               => IN_QUEUE,
                                                    ENQUEUE_OPTIONS          => V_ENQUEUE_OPTIONS,
                                                    ARRAY_SIZE               => V_CONTATTI_MESSAGE_BODY_ARRAY.COUNT,
                                                    MESSAGE_PROPERTIES_ARRAY => V_MSG_PROPERTIES_TABLE,
                                                    PAYLOAD_ARRAY            => V_CONTATTI_MESSAGE_BODY_ARRAY,
                                                    msgid_array              => V_MESSAGE_HANDLE_ARRAY
                                            );

                    END IF;

                    Q_END := DBMS_UTILITY.GET_TIME;
                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE  (JOB ID: ' || JOB_ID || ') - ENQUEUED  '||  V_ENQUEUED_CNT  || ' MESSAGES INTO ' || IN_QUEUE  || '(elapsed:'|| (Q_END - Q_START)/100 ||' s)', ADC_PKG_COMMON.DEBUG_LEVEL, INPUT_ID_SESSION,IS_DEBUG_ENABLED);  
                    MESSAGE_COUNT := MESSAGE_COUNT + V_ENQUEUED_CNT;

                    L_KEY := LISTA_MESSAGGI_RIMANENTI.first;

                    LOOP

                      EXIT WHEN L_KEY IS NULL;

                      -- dbms_output.put_line(LISTA_MESSAGGI_RIMANENTI(L_KEY) || ' - ' || L_KEY);

                      UPDATE ADC_TX_JOBID_SESSION_BIC_EXP SET N_MESSAGGI_RIMANENTI = N_MESSAGGI_RIMANENTI + LISTA_MESSAGGI_RIMANENTI(L_KEY)
                      WHERE
                      FLUSSO_ID = TO_NUMBER(L_KEY);

                      LISTA_MESSAGGI_RIMANENTI(L_KEY) := 0;

                      L_KEY := LISTA_MESSAGGI_RIMANENTI.next(L_KEY);

                    END LOOP;

                    COMMIT; /* ACCODO I BLOCK_SIZE NUM RECORD */

                    COMMIT_COUNT := COMMIT_COUNT + 1;

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE (JOB ID: ' || JOB_ID || ') - COMMIT #' || COMMIT_COUNT || ' EXECUTED. READ: ' || ROW_COUNT 
                                                                                                    || ' CONTACTS , OK MSG IN ' || IN_QUEUE  ||':' || MESSAGE_COUNT
                                                                                                    || ', BAD MSG IN ADC_BAD_TX_CONTATTI :' || BAD_MESSAGE_COUNT
                                                                                                    , ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_SESSION,IS_DEBUG_ENABLED);   
                EXIT WHEN V_CONTATTI_TX.COUNT < BLOCK_SIZE;

            END LOOP;

        CLOSE ADC_TX_CONTATTI_CUR;
        L_END := DBMS_UTILITY.GET_TIME ;  -- Start Time
        LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'ENQUEUE_CONTATTI_RANGE (JOB ID: ' || JOB_ID || ') - END (elapsed: '|| (L_END - L_START)/100 ||' s): READ: ' || ROW_COUNT 
                                                                                                    || ' CONTACTS, OK MSG IN ' || IN_QUEUE ||':' || MESSAGE_COUNT
                                                                                                    || ', BAD MSG IN ADC_BAD_TX_CONTATTI:' || BAD_MESSAGE_COUNT
                                                                                                    , ADC_PKG_COMMON.INFO_LEVEL,INPUT_ID_SESSION);

        DBMS_OUTPUT.PUT_LINE('PROCEDURE: ENQUEUE_CONTATTI_RANGE (JOB ID: ' || JOB_ID || ' ) - END (elapsed:'|| (L_END - L_START)/100 ||' s): READ: ' || ROW_COUNT 
                                                                                                    || ' CONTACTS, OK MSG IN' || IN_QUEUE ||':' || MESSAGE_COUNT
                                                                                                    || ', BAD MSG IN ADC_BAD_TX_CONTATTI:' || BAD_MESSAGE_COUNT);   
        BEGIN  
          OPEN SESSION_ENQUEUERS_CUR;
              LOOP 
                  FETCH SESSION_ENQUEUERS_CUR INTO ACTIVE_ENQUEUER_NUMBER;
                  EXIT WHEN SESSION_ENQUEUERS_CUR%NOTFOUND;

                  UPDATE ADC_TX_JOBID_SESSION SET ACTIVE_ENQUEUER=ACTIVE_ENQUEUER_NUMBER-1 WHERE CURRENT OF SESSION_ENQUEUERS_CUR;
              END LOOP;
          CLOSE SESSION_ENQUEUERS_CUR;
        EXCEPTION WHEN OTHERS THEN 
          CLOSE SESSION_ENQUEUERS_CUR;
        END;
    END ENQUEUE_CONTATTI_RANGE;

