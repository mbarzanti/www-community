            UPDATE ADC_ANAGRAFICA_DB_ZONA SET VARIAZIONE = 1, DATA_ULTIMA_VARIAZIONE = SYSTIMESTAMP, INTERESSE_DB_ZONA = V_INTERESSE_DB_ZONA WHERE ID_ANAGRAFICA_BASE = V_ID_ANAGRAFICA_BASE_IN;
            INSERT INTO ADC_DB_ZONA_ANAG_TO_EXPORT (ID_ANAGRAFICA_BASE, IN_LAVORAZIONE) VALUES (V_ID_ANAGRAFICA_BASE_IN,0);

            DIAGNOSTIC_RESULT := ADC_PKG_COMMON.LOGGER(DIAGNOSTIC_LN, '[' || DIAGNOSTIC_CODE || '-E-00040' || ']', DIAGNOSTIC_INFO_LEVEL,TID);

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_INDIRIZZI (JOB ID: ' || JOB_ID || ') - AGGIORNATA ANAGRAFICA PER DB ZONA - ANAGRAFICA_BASE - ' || V_ID_ANAGRAFICA_BASE_IN , ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_INDIRIZZI (JOB ID: ' || JOB_ID || ') - END', ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

    END;

