                IF rigaIndirizzi.ID_CIVICO IS NOT NULL AND ((V_TIPO_CLIENTE_FONTE='R' AND rigaIndirizzi.ID_TIPO_INDIRIZZO IN (2,6)) OR (V_TIPO_CLIENTE_FONTE='B' AND rigaIndirizzi.ID_TIPO_INDIRIZZO=5) AND V_INTERESSE_DB_ZONA!=1) THEN
