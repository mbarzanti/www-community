        l_start       NUMBER;
        l_end         NUMBER;
        LOGRESULT     NUMBER;

        idClienteAuc varchar2(100);
        idAnagraficaBase number;

        clienteBusinessNode xmltype;
        clienteRetailNode xmltype;
        listaIndirizziNode xmltype;
        listaContattiNode xmltype;
        listaFigureCorrelateNode xmltype;

        creaClienteRetailMessage boolean;
        creaClienteBusinessMessage boolean;
        creaContattiMessage boolean;
        creaIndirizziMessage boolean;
        creaFigureCorrelateMessage boolean;

        V_CLIENTI_B_MESSAGE_BODY        AUC_DG_CLIENTI_BUSINESS_MSG_T;
        V_CLIENTI_R_MESSAGE_BODY        AUC_DG_CLIENTI_RETAIL_MSG_T;
        V_CONTATTI_MESSAGE_BODY         AUC_DG_CONTATTI_MSG_TA;
        V_INDIRIZZI_MESSAGE_BODY        AUC_DG_INDIRIZZI_MSG_TA;
        V_FIGURE_CORR_MESSAGE_BODY      AUC_DG_FIGURE_CORR_MSG_TA;

        V_ANAGRAFICA_UNICA_MSG_BODY    AUC_DG_GOLDEN_MESSAGE_T;
        V_ANAG_UNICA_ERR_MSG_BODY    AUC_DG_GOLDEN_MESSAGE_T;

        V_ENQUEUE_OPTIONS           DBMS_AQ.ENQUEUE_OPTIONS_T;
        V_MESSAGE_PROPERTIES        DBMS_AQ.MESSAGE_PROPERTIES_T;
        IN_QUEUE                    VARCHAR2(100);
        V_MESSAGE_HANDLE            RAW(16);
        BAD_MESSAGE     BOOLEAN;

        V_ERR_ENQUEUE_OPTIONS           DBMS_AQ.ENQUEUE_OPTIONS_T;
        V_ERR_MESSAGE_PROPERTIES        DBMS_AQ.MESSAGE_PROPERTIES_T;  
        ERROR_QUEUE                     VARCHAR2(100);
        ERRMESSAGE VARCHAR(32000);
        V_ULTIMA_MODIFICA_CLIENTE TIMESTAMP (6);
        V_ULTIMA_MODIFICA_CONTATTI TIMESTAMP(6);
        V_ULTIMA_MODIFICA_INDIRIZZI TIMESTAMP(6);
        V_ULTIMA_MODIFICA_FIGURE_CORR TIMESTAMP(6);

        CLIENTE_NOT_TRACE BOOLEAN;
        NULL_DATE TIMESTAMP := TO_TIMESTAMP('19000101','yyyymmdd');

         --diagnostic variables
        DIAGNOSTIC_CODE VARCHAR2(512):='AAU9006';
        DIAGNOSTIC_LN VARCHAR2(512):=ADC_PKG_LOAD_AUC_DG.DIAGNOSTIC_LOGGER_NAME;
        DIAGNOSTIC_INFO_LEVEL VARCHAR2(512):=ADC_PKG_COMMON.INFO_LEVEL;
