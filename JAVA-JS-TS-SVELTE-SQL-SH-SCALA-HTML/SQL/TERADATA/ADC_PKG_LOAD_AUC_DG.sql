          GLOBAL_START := DBMS_UTILITY.GET_TIME ;  -- Start Time

          V_VIRTUAL_QUEUE := SUBSTR(IN_QUEUE  ,3,LENGTH(IN_QUEUE) -5);
          BEGIN 
              SELECT PARAMETER_VALUE INTO DEQUEUE_BLOCK_SIZE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='DEQUEUE_BLOCK_SIZE' AND ROWNUM = 1;
