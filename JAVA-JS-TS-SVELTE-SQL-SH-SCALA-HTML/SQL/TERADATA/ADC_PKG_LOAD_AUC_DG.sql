                    V_ANAGRAFICA_UNICA_MSG_BODY.AUC_DG_CONTATTI            := V_CONTATTI_MESSAGE_BODY;

                    V_MESSAGE_PROPERTIES.USER_PROPERTY := SYS.ANYDATA.CONVERTVARCHAR2(TID);

                    GET_ONLINE_QUEUE_NAME(idClienteAuc,IN_QUEUE);

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - ENQUEUING INTO QUEUE ' || IN_QUEUE, ADC_PKG_COMMON.DEBUG_LEVEL, TID);

                    DBMS_AQ.ENQUEUE(
                        queue_name              => IN_QUEUE,
                        enqueue_options         => V_ENQUEUE_OPTIONS,
                        message_properties      => v_message_properties,
                        PAYLOAD                 => V_ANAGRAFICA_UNICA_MSG_BODY,
                        MSGID                   => V_MESSAGE_HANDLE
