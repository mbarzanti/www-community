	PROCEDURE DEQUEUE_CONTATTI(JOB_ID VARCHAR2, IN_QUEUE VARCHAR2, ERROR_QUEUE VARCHAR2, V_SCHEDULING_INTERVAL NUMBER, MESSAGE OUT VARCHAR2,ESITO OUT VARCHAR2) AS

        -- not change
        msgid                     RAW (16);

        ESITOOPERAZIONE                 VARCHAR2(100);
        INSERTED_ID_USAGE               VARCHAR2(100);
        LOGRESULT                       NUMBER;
        L_START                         NUMBER;
        L_END                           NUMBER;
        GLOBAL_START                    NUMBER;
        GLOBAL_END                      NUMBER;
        INPUT_ID_FLUSSO                 NUMBER;

        DEQUEUED_MESSAGE                NUMBER;
        CURRENT_DEQUEUED_MESSAGE        NUMBER;
        DEQUEUE_BLOCK_SIZE              NUMBER;

        no_messages                     exception;

        V_CONTATTI_MESSAGE_BODY        AUC_DG_CONTATTI_MSG_TA;

        V_ENQUEUE_OPTIONS               DBMS_AQ.ENQUEUE_OPTIONS_T;
        V_DEQUEUE_OPTIONS               DBMS_AQ.DEQUEUE_OPTIONS_T;
        V_MESSAGE_PROPERTIES            DBMS_AQ.MESSAGE_PROPERTIES_T;
        V_MESSAGE_PROPERTIES_ENQ        DBMS_AQ.MESSAGE_PROPERTIES_T;
        V_MESSAGE_HANDLE_ARRAY          DBMS_AQ.MSGID_ARRAY_T;
