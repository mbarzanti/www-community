                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - MESSAGE ' || V_MESSAGE_HANDLE || ' ENQUEUED INTO QUEUE ' || IN_QUEUE, ADC_PKG_COMMON.DEBUG_LEVEL, TID);

                ELSE  

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - GOLDEN RECORD SCARTATO ', ADC_PKG_COMMON.ERROR_LEVEL, TID);

                    V_ANAG_UNICA_ERR_MSG_BODY                         := AUC_DG_GOLDEN_MESSAGE_T();
                    V_ANAG_UNICA_ERR_MSG_BODY.ID_CLIENTE_AUC          := idClienteAuc;
                    V_ANAG_UNICA_ERR_MSG_BODY.SCARTATO := 1;
                    V_ANAG_UNICA_ERR_MSG_BODY.MOTIVO_SCARTO := ERRMESSAGE;

