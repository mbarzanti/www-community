            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| ID_CLIENTE_AUC ||'] INSERIMENTO_INDIRIZZI (JOB ID: ' || JOB_ID || ') - CANCELLATI INDIRIZZI PER ID_CLIENTE_BIC: ' || ID_CLIENTE_AUC || ' E ANAG_BASE: ' || V_ID_ANAGRAFICA_BASE_IN, ADC_PKG_COMMON.DEBUG_LEVEL, TID, IS_DEBUG_ENABLED);

