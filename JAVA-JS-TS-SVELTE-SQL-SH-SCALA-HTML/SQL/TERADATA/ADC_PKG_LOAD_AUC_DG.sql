                END IF;
            END IF;

            l_end := DBMS_UTILITY.GET_TIME ; 

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] ACQUISIZIONE_ANAGRAFICA_UNICA - END (elapsed:'|| (l_end - l_start)/100 ||' s)', ADC_PKG_COMMON.INFO_LEVEL, TID);  

    END; 

    PROCEDURE GET_ONLINE_QUEUE_NAME(IDCLIENTEAUC VARCHAR2, QUEUE_NAME OUT VARCHAR2) IS

        QUEUE_NUMBER PLS_INTEGER;
        QUEUES_NUMBER PLS_INTEGER;
        QUEUE_SUFFIX VARCHAR2(10);

        V_VIRTUAL_QUEUE VARCHAR2(255);
        V_VIRTUAL_QUEUE_CHIAVE VARCHAR2(255);
        V_QUEUE_NUMBER_CHIAVE VARCHAR2(255);

        BEGIN

        V_VIRTUAL_QUEUE_CHIAVE := AUC_DG_VQ_PREF_PARAM;
        V_VIRTUAL_QUEUE :=  SYS_CONTEXT(CONTEXT_NAME, V_VIRTUAL_QUEUE_CHIAVE);

        IF(V_VIRTUAL_QUEUE IS NULL) THEN

          BEGIN
              SELECT VALORE INTO V_VIRTUAL_QUEUE FROM ADC_SYS_CONFIG ASCONF WHERE ASCONF.CHIAVE = V_VIRTUAL_QUEUE_CHIAVE AND ROWNUM = 1;
          EXCEPTION WHEN NO_DATA_FOUND THEN
              V_VIRTUAL_QUEUE:= VIRTUAL_QUEUE;
          END;


        /* ASSEGNARE I PRIVILEGI PER IL CONTEXT */
          DBMS_SESSION.SET_CONTEXT(CONTEXT_NAME, V_VIRTUAL_QUEUE_CHIAVE, V_VIRTUAL_QUEUE);

        END IF;

        V_QUEUE_NUMBER_CHIAVE := 'Q_NUMBER_' || V_VIRTUAL_QUEUE;

        QUEUES_NUMBER :=  SYS_CONTEXT(CONTEXT_NAME, V_QUEUE_NUMBER_CHIAVE);

        IF(QUEUES_NUMBER IS NULL) THEN
            BEGIN
                SELECT PARAMETER_VALUE INTO QUEUES_NUMBER FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='QUEUE_NUMBER'  AND ROWNUM = 1;
            EXCEPTION WHEN NO_DATA_FOUND THEN
                QUEUES_NUMBER:= 1;
            END;

        /* ASSEGNARE I PRIVILEGI PER IL CONTEXT */
          DBMS_SESSION.SET_CONTEXT(CONTEXT_NAME, V_QUEUE_NUMBER_CHIAVE, QUEUES_NUMBER);
        END IF;

        QUEUE_NUMBER := MOD(TO_NUMBER(IDCLIENTEAUC) , QUEUES_NUMBER) + 1;
        QUEUE_SUFFIX := '0'|| QUEUE_NUMBER;
        QUEUE_NAME   :=  'Q_' || V_VIRTUAL_QUEUE || '_' || SUBSTR(QUEUE_SUFFIX, LENGTH(QUEUE_SUFFIX) -1);

    END;

