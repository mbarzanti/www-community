              CURRENT_DEQUEUED_MESSAGE := CURRENT_DEQUEUED_MESSAGE +1;


              INPUT_ID_FLUSSO :=  SYS.ANYDATA.accessNumber(V_MESSAGE_PROPERTIES.user_property); 

               LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - Scodato messaggio (' ||  MSGID || ')'  , ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_FLUSSO,IS_DEBUG_ENABLED);  

               LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - Creazione oggetti per gestione dei CONTATTI '  , ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_FLUSSO,IS_DEBUG_ENABLED);

              /*GESTIONE MESSAGGIO */

              BEGIN    

                SAVEPOINT GESTIONE_SINGOLO_CONTATTO;

                V_CONTATTI_TX_TABLE := V_CONTATTI_MESSAGE_BODY.CONTATTI_TX_TABLE;

                INSERIMENTO_CONTATTI(
                            IS_DEBUG_ENABLED  => IS_DEBUG_ENABLED,
                            TID => MSGID,
                            JOB_ID => JOB_ID,
                            VIRTUAL_QUEUE => V_VIRTUAL_QUEUE,
                            ID_ANAGRAFICA_BASE => NULL,
                            TIPO_CLIENTE_FONTE => NULL,
                            CONTATTI => V_CONTATTI_MESSAGE_BODY
                ); 


                J := V_CONTATTI_TX_TABLE.FIRST;

                WHILE J IS NOT NULL LOOP

                    BEGIN

                      IF LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) IS NOT NULL THEN                                             
                         V_N_MESSAGGI_SCODATI := LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) + 1;
                         LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) := V_N_MESSAGGI_SCODATI;
                      END IF;

                   EXCEPTION WHEN NO_DATA_FOUND THEN

                      LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) := 1;                                                     

                   END;

                    j := V_CONTATTI_TX_TABLE.NEXT(j);

                END LOOP;

              EXCEPTION 

              WHEN ANAGRAFICA_MANCANTE THEN

                  LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - CONTATTI CON ID_CLIENTE_AUC (' ||  V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC || ') ASSOCIATA AD ANAGRAFICA INESISTENTE'  , ADC_PKG_COMMON.ERROR_LEVEL,INPUT_ID_FLUSSO);
                  ROLLBACK TO GESTIONE_SINGOLO_CONTATTO;

                  BEGIN
                    select valore into MAXRETRY from ADC_SYS_CONFIG where chiave = 'MAX_RETRY_ANAG_CORR';
                    EXCEPTION WHEN NO_DATA_FOUND THEN
                    MAXRETRY :=3;
                  END;

                  BEGIN
                    select valore into SLEEP_SEC from ADC_SYS_CONFIG where chiave = 'SLEEP_SEC_RETRY_ANAG_CORR';
                    EXCEPTION WHEN NO_DATA_FOUND THEN
                    SLEEP_SEC :=60*5;
                  END;

                  IF(V_CONTATTI_MESSAGE_BODY.RETRY_COUNT = MAXRETRY) THEN

                      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - CONTATTI CON ID_CLIENTE_AUC (' ||  V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC || ') - ASS. ANAGRAFICA - MASSIMO NUMERO DI TENTATIVI RAGGIUNTO', ADC_PKG_COMMON.INFO_LEVEL,INPUT_ID_FLUSSO);

                      J := V_CONTATTI_TX_TABLE.FIRST;

                      WHILE J IS NOT NULL LOOP

                          --V_CONTATTI_SCARTI_ROW.TIPO_ELABORAZIONE    := V_CONTATTI_TX_TABLE(J).TIPO_ELABORAZIONE;
                          --V_CONTATTI_SCARTI_ROW.COD_CLIENTE_SORGENTE := V_CONTATTI_TX_TABLE(J).COD_CLIENTE_SORGENTE;
                          --V_CONTATTI_SCARTI_ROW.COD_SISTEMA_SORGENTE := V_CONTATTI_TX_TABLE(J).COD_SISTEMA_SORGENTE;
                          V_CONTATTI_SCARTI_ROW.ID_CLIENTE_AUC       := V_CONTATTI_TX_TABLE(J).ID_CLIENTE_AUC;
                          V_CONTATTI_SCARTI_ROW.ID_TIPO_RIFERIMENTO  := V_CONTATTI_TX_TABLE(J).ID_TIPO_RIFERIMENTO;
                          V_CONTATTI_SCARTI_ROW.RIFERIMENTO          := V_CONTATTI_TX_TABLE(J).RIFERIMENTO;
                          --V_CONTATTI_SCARTI_ROW.TIPO_CLIENTE_FONTE   := V_CONTATTI_TX_TABLE(J).TIPO_CLIENTE_FONTE;
                          V_CONTATTI_SCARTI_ROW.DS_TIMESTAMP         := V_CONTATTI_TX_TABLE(J).DS_TIMESTAMP;
                          V_CONTATTI_SCARTI_ROW.ID_FLUSSO            := V_CONTATTI_TX_TABLE(J).ID_FLUSSO;
                          V_CONTATTI_SCARTI_ROW.CONTATORE            := V_CONTATTI_TX_TABLE(J).CONTATORE;
                          V_CONTATTI_SCARTI_ROW.TS_CARICAMENTO       := V_CONTATTI_TX_TABLE(J).TS_CARICAMENTO;
                          V_CONTATTI_SCARTI_ROW.ELABORATO            := V_CONTATTI_TX_TABLE(J).ELABORATO;
                          V_CONTATTI_SCARTI_ROW.SCARTATO             := 1;
                          V_CONTATTI_SCARTI_ROW.MOTIVO_SCARTO        := 'ASS. ANAGRAFICA - MASSIMO NUMERO DI TENTATIVI RAGGIUNTO';
                          V_CONTATTI_SCARTI_ROW.ID                   := V_CONTATTI_TX_TABLE(J).ID;
                          --V_CONTATTI_SCARTI_ROW.COD_CONT_SORGENTE    := V_CONTATTI_TX_TABLE(J).COD_CONT_SORGENTE;
                          V_CONTATTI_SCARTI_ROW.DATA_INSERIMENTO     := V_CONTATTI_TX_TABLE(J).DATA_INSERIMENTO;
                          V_CONTATTI_SCARTI_ROW.PREFISSO     := V_CONTATTI_TX_TABLE(J).PREFISSO;
                          V_CONTATTI_SCARTI_ROW.ID_PREF_NAZIONE     := V_CONTATTI_TX_TABLE(J).ID_PREF_NAZIONE;

                          INSERT INTO ADC_BAD_TX_CONTATTI_DG VALUES V_CONTATTI_SCARTI_ROW;

                          LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - BAD RECORD ADDED INTO ADC_BAD_TX_CONTATTI_DG', ADC_PKG_COMMON.DEBUG_LEVEL,INPUT_ID_FLUSSO,IS_DEBUG_ENABLED);

                          BEGIN

                            IF LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) IS NOT NULL THEN                                             
                               V_N_MESSAGGI_SCODATI := LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) + 1;
                               LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) := V_N_MESSAGGI_SCODATI;
                            END IF;

                         EXCEPTION WHEN NO_DATA_FOUND THEN

                            LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) := 1;                                                     

                         END;

                        j := V_CONTATTI_TX_TABLE.NEXT(j);

                    END LOOP;

                  ELSE

                      V_CONTATTI_MESSAGE_BODY.RETRY_COUNT := V_CONTATTI_MESSAGE_BODY.RETRY_COUNT+1;
                      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - CONTATTI CON ID_CLIENTE_AUC (' ||  V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC || ') - ASS. ANAGRAFICA - POSTICIPATA ELABORAZIONE - TENTATIVO N° '|| V_CONTATTI_MESSAGE_BODY.RETRY_COUNT, ADC_PKG_COMMON.INFO_LEVEL,INPUT_ID_FLUSSO);

                      V_MESSAGE_PROPERTIES_ENQ.USER_PROPERTY := SYS.ANYDATA.CONVERTNUMBER(V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC);  
                      V_MESSAGE_PROPERTIES_ENQ.delay := SLEEP_SEC;

                      ADC_PKG_AQ_FRAMEWORK.MARK_AS_NOT_PURGEABLE(IN_QUEUE);

                      DBMS_AQ.ENQUEUE(
                          queue_name              => IN_QUEUE,
                          enqueue_options         => V_ENQUEUE_OPTIONS,
                          message_properties      => V_MESSAGE_PROPERTIES_ENQ,
                          PAYLOAD                 => V_CONTATTI_MESSAGE_BODY,
                          MSGID                   => V_MESSAGE_HANDLE
                      );

                      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI - MESSAGE ' || V_MESSAGE_HANDLE || ' ENQUEUED INTO QUEUE ' || IN_QUEUE, ADC_PKG_COMMON.DEBUG_LEVEL, INPUT_ID_FLUSSO, IS_DEBUG_ENABLED);

                      -- COMMIT; -- VERIFICARE SE SERVE - AGGIUNTO PER SBLOCCARE IMMEDIATAMENTE EVENTUALI JOB IN ATTESA 

                  END IF;

              WHEN OTHERS THEN
                ROLLBACK TO GESTIONE_SINGOLO_CONTATTO;

                   v_ERR_message_properties.user_property := V_MESSAGE_PROPERTIES.user_property;

                   V_CONTATTI_MESSAGE_BODY.MOTIVO_SCARTO := SUBSTR('ERROR IN INSERTING CONTATTI: ' || SQLERRM || ' - ' || dbms_utility.format_error_backtrace,1,256);

                    DBMS_AQ.ENQUEUE(
                        QUEUE_NAME              => ERROR_QUEUE,
                        ENQUEUE_OPTIONS         => V_ERR_ENQUEUE_OPTIONS,
                        message_properties      => v_ERR_message_properties,
                        PAYLOAD                 => V_CONTATTI_MESSAGE_BODY,
                        MSGID                   => V_MESSAGE_HANDLE
                    );

                    J := V_CONTATTI_TX_TABLE.FIRST;

                    WHILE J IS NOT NULL LOOP

                        BEGIN

                            IF LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) IS NOT NULL THEN                                             
                               V_N_MESSAGGI_SCODATI := LISTA_MESSAGGI_RIMANENTI('' || V_CONTATTI_TX_TABLE(J).ID_FLUSSO) + 1;
