                    SELECT NVL(ULTIMA_MODIFICA_CLIENTE,NULL_DATE) , NVL(ULTIMA_MODIFICA_CONTATTI,NULL_DATE) ,NVL(ULTIMA_MODIFICA_INDIRIZZI,NULL_DATE),NVL(ULTIMA_MODIFICA_FIGURE_CORR,NULL_DATE) INTO V_ULTIMA_MODIFICA_CLIENTE, V_ULTIMA_MODIFICA_CONTATTI, V_ULTIMA_MODIFICA_INDIRIZZI,V_ULTIMA_MODIFICA_FIGURE_CORR
                    FROM ADC_AUC_DG_TRACE
                    WHERE ID_CLIENTE_BIC = idClienteAuc;
                EXCEPTION WHEN NO_DATA_FOUND  THEN
                    CLIENTE_NOT_TRACE := TRUE;
