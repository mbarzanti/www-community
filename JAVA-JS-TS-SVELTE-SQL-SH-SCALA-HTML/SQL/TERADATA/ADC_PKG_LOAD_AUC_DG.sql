            BEGIN           

                V_CLIENTI_B_MESSAGE_BODY := AUC_DG_CLIENTI_BUSINESS_MSG_T();

                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:dsTimestamp', ns)=1) THEN DS_TIMESTAMP := to_timestamp(clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:dsTimestamp/text()', ns).getStringVal(),'yyyy-MM-dd HH24:MI:SS'); END IF;

                IF (clienteBusinessNode.existsNode('/cmf:clienteBusiness/cmf:clienteProspect', ns)=1) THEN V_CLIENTI_B_MESSAGE_BODY.CLIENTE_PROSPECT := clienteBusinessNode.extract( '/cmf:clienteBusiness/cmf:clienteProspect/text()', ns).getStringVal(); END IF;
