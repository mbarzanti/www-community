                  L_KEY := LISTA_MESSAGGI_RIMANENTI.next(L_KEY);

                END LOOP;

                COMMIT;
                CURRENT_DEQUEUED_MESSAGE:=0;
            END IF;

            EXIT WHEN ((L_END - GLOBAL_START)/100 )> V_SCHEDULING_INTERVAL;
      END LOOP;

      L_KEY := LISTA_MESSAGGI_RIMANENTI.first;

      LOOP

        EXIT WHEN L_KEY IS NULL;

                      -- dbms_output.put_line(LISTA_MESSAGGI_RIMANENTI(L_KEY) || ' - ' || L_KEY);

        UPDATE ADC_TX_JOBID_SESSION_BIC_EXP SET N_MESSAGGI_RIMANENTI = N_MESSAGGI_RIMANENTI - LISTA_MESSAGGI_RIMANENTI(L_KEY)
        WHERE
        FLUSSO_ID = TO_NUMBER(L_KEY);

        LISTA_MESSAGGI_RIMANENTI(L_KEY) := 0;

        L_KEY := LISTA_MESSAGGI_RIMANENTI.next(L_KEY);

      END LOOP;
      COMMIT;
      GLOBAL_END := DBMS_UTILITY.GET_TIME ;  -- Start Time
      LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ' ) - END  -  Messages : ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE ||' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)'  , ADC_PKG_COMMON.INFO_LEVEL,'');  
      DBMS_OUTPUT.PUT_LINE('PROCEDURE: DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ' ) - END - Messages: ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE || ' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)');  

      ADC_PKG_COMMON.FLUSH_LOGGER(DIAGNOSTIC_LN);

      EXCEPTION
        WHEN NO_MESSAGES THEN

          L_KEY := LISTA_MESSAGGI_RIMANENTI.first;

          LOOP

            EXIT WHEN L_KEY IS NULL;

                      -- dbms_output.put_line(LISTA_MESSAGGI_RIMANENTI(L_KEY) || ' - ' || L_KEY);

            UPDATE ADC_TX_JOBID_SESSION_BIC_EXP SET N_MESSAGGI_RIMANENTI = N_MESSAGGI_RIMANENTI - LISTA_MESSAGGI_RIMANENTI(L_KEY)
            WHERE
            FLUSSO_ID = TO_NUMBER(L_KEY);

            LISTA_MESSAGGI_RIMANENTI(L_KEY) := 0;

            L_KEY := LISTA_MESSAGGI_RIMANENTI.next(L_KEY);

          END LOOP;
          COMMIT;

            ADC_PKG_AQ_FRAMEWORK.SAFE_PURGE_QUEUE(IN_QUEUE);

            /* ABBASSA IL HWM */
            /* BEGIN
                --PO_T.block:=TRUE;
                SELECT QUEUE_TABLE INTO QUEUE_TABLE FROM USER_QUEUES WHERE NAME=IN_QUEUE;
                --EXECUTE IMMEDIATE 'SELECT COUNT(QUEUE) FROM AQ$'|| QUEUE_TABLE INTO MESSAGE_NUMBER;
                /* IF(MESSAGE_NUMBER = 0 ) THEN */
                  /* DBMS_AQADM.PURGE_QUEUE_TABLE(
                      QUEUE_TABLE,
                      NULL,
                      PO_T  -- AGGIUNGERE IL LOCK?
                  );
                /* END IF; */
            /* EXCEPTION WHEN NO_DATA_FOUND THEN
              LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || SQLERRM || ' error in purging queue ' || IN_QUEUE, ADC_PKG_COMMON.ERROR_LEVEL,'');
            END; */

            GLOBAL_END := DBMS_UTILITY.GET_TIME ;  -- Start Time
            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_CONTATTI (JOB ID: ' || JOB_ID || ') - END (NO MORE MESSAGES) - Messages: ' || DEQUEUED_MESSAGE || ' dequeued from queue ' || IN_QUEUE || ' (elapsed:'|| (GLOBAL_END - GLOBAL_START)/100 ||' s)'  , ADC_PKG_COMMON.INFO_LEVEL,'');
