                                            CONTATTI => V_CONTATTI_MESSAGE);            

                        END IF;

                    ELSE
                        LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'DEQUEUE_AUC_GOLDEN_RECORD (JOB ID: ' || JOB_ID || ') - ERRORE NELL''INSERIMENTO DELL''ANAGRAFICA- ID_ANGRAFICA_BASE := NULL, GOLDEN RECORD SCARTATO  (' ||  MSGID || ') ' , ADC_PKG_COMMON.ERROR_LEVEL,TID);
                   END IF;
             EXCEPTION WHEN OTHERS THEN

