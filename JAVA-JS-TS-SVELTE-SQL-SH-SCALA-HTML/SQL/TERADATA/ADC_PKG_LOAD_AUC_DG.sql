	PROCEDURE INIT_ENQUEUE_CONTATTI(INPUT_ID_SESSION NUMBER,  V_VIRTUAL_QUEUE VARCHAR2, MESSAGE OUT VARCHAR2,ESITO OUT VARCHAR2) IS

        MIN_ROWNUM NUMBER;
        MAX_ROWNUM NUMBER;

        MIN_ID_CLIENTE_AUC NUMBER;
        MAX_ID_CLIENTE_AUC NUMBER;

        USAGE_BLOCK NUMBER;
        CURRENT_MIN_CONTATTO NUMBER;
        CURRENT_MAX_CONTATTO NUMBER;
        CURRENT_MIN_ID_CLIENTE_AUC   NUMBER;
        CURRENT_MAX_ID_CLIENTE_AUC   NUMBER;

        LOGRESULT         NUMBER;

        TYPE QUEUES_TABLE IS TABLE OF VARCHAR2(100) INDEX BY PLS_INTEGER;
        QUEUE_INDEX                 NUMBER;
        QUEUES                      QUEUES_TABLE;
        QUEUE_NUMBER                NUMBER;

        V_QUEUE                       VARCHAR2(255);
        BAD_RECORD_QUEUE              VARCHAR2(255);
        ENQUEUE_PROCEDURE             VARCHAR(255);
        STARTUP_PROCEDURE             VARCHAR(255);
        ENABLED                       VARCHAR2(10);
        QUEUE_SUFFIX                  VARCHAR2(10);
        BLOCK_SIZE                    NUMBER;
        NAME_JOB                      VARCHAR2(255);
        ACTIVE_ENQUEUER_JOB_THRESHOLD VARCHAR2(255);
        ACTUAL_JOB_COUNT              NUMBER;
        V_JOB_CREATOR                 VARCHAR2(255) :=  $$PLSQL_UNIT_OWNER;
        TABLE_NAME                    VARCHAR2(100);

        PROCEDURE_CALL                VARCHAR2(1000);
        IN_ROWNUM                     VARCHAR2(1000); 

        TYPE PARALLEL_RECORD_T IS RECORD ( 
          ROW_NUM                  NUMBER,
          ID                       NUMBER
        );

        TYPE PARALLEL_TABLE_T IS TABLE OF PARALLEL_RECORD_T INDEX BY PLS_INTEGER;

        TYPE ROWNUMS_T IS TABLE OF NUMBER INDEX BY PLS_INTEGER;

        PARALLEL_RECORD               PARALLEL_RECORD_T;
        PARALLEL_TABLE                PARALLEL_TABLE_T;
        ROWNUMS                       ROWNUMS_T;
        TMP_ROW_NUM                   NUMBER;
        TMP_ID                        NUMBER;
        I_QUEUEE                      NUMBER; 

        queryContatti                 VARCHAR2(1000);
        V_REF_CURSOR                  SYS_REFCURSOR;
        V_CUR_HDL                     NUMBER;
        v_ignore                      INTEGER;

        COUNTER                       PLS_INTEGER;


        CURSOR SESSION_ENQUEUERS_CUR IS
            SELECT ACTIVE_ENQUEUER FROM ADC_TX_JOBID_SESSION S WHERE SESSION_ID=INPUT_ID_SESSION AND VIRTUAL_QUEUE = V_VIRTUAL_QUEUE FOR UPDATE;

        ACTIVE_ENQUEUER_NUMBER          NUMBER;

        BEGIN

             LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - BEGIN ', ADC_PKG_COMMON.INFO_LEVEL,INPUT_ID_SESSION);  

			BEGIN 
				SELECT PARAMETER_VALUE INTO ENABLED FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='ENABLED' AND ROWNUM = 1;
			EXCEPTION WHEN NO_DATA_FOUND THEN
				SELECT PARAMETER_VALUE INTO ENABLED FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'DEFAULT' AND AQC.PARAMETER_TYPE='ENABLED' AND ROWNUM = 1;
			END;

			/* ACTIVE_ENQUEUER_JOB_THRESHOLD */
			BEGIN 
              SELECT PARAMETER_VALUE INTO ACTIVE_ENQUEUER_JOB_THRESHOLD FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'FINALIZE_LOAD_USAGE' AND AQC.PARAMETER_TYPE='ACTIVE_ENQUEUER_JOB_THRESHOLD' AND ROWNUM = 1;
            EXCEPTION WHEN NO_DATA_FOUND THEN
               ACTIVE_ENQUEUER_JOB_THRESHOLD := 20;
            END;


			/* TABLE_NAME NAME  - OBBLIGATORIO */
			SELECT PARAMETER_VALUE INTO TABLE_NAME FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='SOURCE_TABLE' AND ROWNUM = 1;

			IF(UPPER(ENABLED) = 'TRUE') THEN

                SELECT COUNT(JOB_NAME) INTO ACTUAL_JOB_COUNT FROM USER_SCHEDULER_JOBS WHERE JOB_NAME LIKE '%ENQ_%' AND JOB_CREATOR = V_JOB_CREATOR;

                IF(ACTUAL_JOB_COUNT < ACTIVE_ENQUEUER_JOB_THRESHOLD) THEN 

					BEGIN 
						SELECT PARAMETER_VALUE INTO QUEUE_NUMBER FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='QUEUE_NUMBER' AND ROWNUM = 1;
					EXCEPTION WHEN NO_DATA_FOUND THEN
						SELECT PARAMETER_VALUE INTO QUEUE_NUMBER FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'DEFAULT' AND AQC.PARAMETER_TYPE='QUEUE_NUMBER' AND ROWNUM = 1;
					END;

					QUEUE_INDEX :=1;
					--FOR V_QUEUE IN (SELECT PARAMETER_VALUE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND PARAMETER_TYPE='QUEUE_MEMBER') LOOP
					FOR I IN 1..QUEUE_NUMBER LOOP 

						QUEUE_SUFFIX := '0'||I;

						--DBMS_OUTPUT.PUT_LINE(V_VIRTUAL_QUEUE || '_' || SUBSTR(QUEUE_SUFFIX, LENGTH(QUEUE_SUFFIX) -1 ));
						V_QUEUE       :=  'Q_'  || V_VIRTUAL_QUEUE || '_' || SUBSTR(QUEUE_SUFFIX, LENGTH(QUEUE_SUFFIX) -1);
						--V_QUEUE_TABLE :=  'QT_' || V_VIRTUAL_QUEUE || '_' || SUBSTR(QUEUE_SUFFIX, LENGTH(QUEUE_SUFFIX) -1);
						QUEUES(QUEUE_INDEX):= V_QUEUE;
						QUEUE_INDEX := QUEUE_INDEX + 1;
					END LOOP;

					BAD_RECORD_QUEUE := 'Q_BAD_' ||V_VIRTUAL_QUEUE;

					BEGIN 
						SELECT PARAMETER_VALUE INTO ENQUEUE_PROCEDURE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='ENQUEUE_PROCEDURE'  AND ROWNUM = 1;
					EXCEPTION WHEN NO_DATA_FOUND THEN
						SELECT PARAMETER_VALUE INTO ENQUEUE_PROCEDURE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'DEFAULT' AND AQC.PARAMETER_TYPE='ENQUEUE_PROCEDURE'  AND ROWNUM = 1;
					END;

					BEGIN 
						SELECT PARAMETER_VALUE INTO BLOCK_SIZE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='ENQUEUE_BLOCK_SIZE' AND ROWNUM = 1;
					EXCEPTION WHEN NO_DATA_FOUND THEN
						SELECT PARAMETER_VALUE INTO BLOCK_SIZE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = 'DEFAULT' AND AQC.PARAMETER_TYPE='ENQUEUE_BLOCK_SIZE' AND ROWNUM = 1;
					END;

					BEGIN 
						SELECT PARAMETER_VALUE INTO STARTUP_PROCEDURE FROM ADC_QUEUES_CONFIG AQC WHERE AQC.VIRTUAL_QUEUE = V_VIRTUAL_QUEUE AND AQC.PARAMETER_TYPE='STARTUP_PROCEDURE' AND ROWNUM = 1;
					EXCEPTION WHEN NO_DATA_FOUND THEN
						STARTUP_PROCEDURE:= NULL;
					END;


					QUEUE_NUMBER:= QUEUES.COUNT;

					MIN_ROWNUM := 1;

					EXECUTE IMMEDIATE 'SELECT COUNT(DISTINCT(NVL(U.ID_CLIENTE_AUC,0))) FROM ' || TABLE_NAME || ' U, ADC_TX_JOBID_SESSION J WHERE U.ID_FLUSSO = J.FLUSSO_ID AND J.VIRTUAL_QUEUE='''|| V_VIRTUAL_QUEUE ||''' AND J.SESSION_ID = '||INPUT_ID_SESSION INTO MAX_ROWNUM;

					IF(MAX_ROWNUM IS NOT NULL AND MAX_ROWNUM > 0) THEN

						IF((MAX_ROWNUM - MIN_ROWNUM) < QUEUE_NUMBER) THEN 
							IF(MAX_ROWNUM = MIN_ROWNUM) THEN 
                            QUEUE_NUMBER :=1;      
                            USAGE_BLOCK  := 0;
                        ELSE
                            QUEUE_NUMBER  := MAX_ROWNUM - MIN_ROWNUM;
                            USAGE_BLOCK   := 1;
                        END IF;
                    ELSE
                        USAGE_BLOCK := FLOOR((MAX_ROWNUM - MIN_ROWNUM )/QUEUE_NUMBER);
                    END IF;

                    BEGIN                                                                                            
                        OPEN SESSION_ENQUEUERS_CUR;
                        LOOP 
                            FETCH SESSION_ENQUEUERS_CUR INTO ACTIVE_ENQUEUER_NUMBER;
                            EXIT WHEN SESSION_ENQUEUERS_CUR%NOTFOUND;
                            UPDATE ADC_TX_JOBID_SESSION SET ACTIVE_ENQUEUER = QUEUE_NUMBER 
                            WHERE SESSION_ID = INPUT_ID_SESSION AND VIRTUAL_QUEUE = V_VIRTUAL_QUEUE;
                        END LOOP;
                        CLOSE SESSION_ENQUEUERS_CUR;
                    EXCEPTION WHEN OTHERS THEN 
						LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - IMPOSSIBILE IMPOSTARE IL NUMERO DI ACCODATORI ATTIVI PER LA SESSIONE ' ||  INPUT_ID_SESSION, ADC_PKG_COMMON.ERROR_LEVEL, INPUT_ID_SESSION);  
                        CLOSE SESSION_ENQUEUERS_CUR;
                    END;

                    DBMS_OUTPUT.PUT_LINE(USAGE_BLOCK);

                    DBMS_OUTPUT.PUT_LINE(MIN_ROWNUM || '-->' || MAX_ROWNUM);
                    DBMS_OUTPUT.PUT_LINE(QUEUE_NUMBER);

                    LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - USING ' || QUEUE_NUMBER || ' QUEUE FOR LOADING DATA', ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION); 

                    /* COSTRUISCE LA CONDIZIONE DEI ROW NUM PER LA RICERCA DEGLI ID_CLIENTE_BIC ASSOCIATI */

                    IN_ROWNUM := '';

                    FOR I IN 1..QUEUE_NUMBER LOOP

                        IF(I > 1) THEN
							IN_ROWNUM := IN_ROWNUM || ',';
                        END IF;

                        CURRENT_MIN_CONTATTO := (MIN_ROWNUM + (I-1) * USAGE_BLOCK) + 1 ;
                        CURRENT_MAX_CONTATTO := MIN_ROWNUM + (I) * USAGE_BLOCK;

                        IF( I = 1) THEN
                          CURRENT_MIN_CONTATTO := MIN_ROWNUM;
                        ELSE 
                          IF( I = QUEUE_NUMBER) THEN
                            CURRENT_MAX_CONTATTO := MAX_ROWNUM;
                          END IF;
                        END IF;

                        IN_ROWNUM := IN_ROWNUM || CURRENT_MIN_CONTATTO || ',' || CURRENT_MAX_CONTATTO;

                        ROWNUMS(I+(I-1)):= CURRENT_MIN_CONTATTO;
                        ROWNUMS(I +(I)):= CURRENT_MAX_CONTATTO;

                    END LOOP;

                    queryContatti := 'SELECT ROW_NUM, ID 
                                        FROM (SELECT ROWNUM AS ROW_NUM, ID_CLIENTE_AUC AS ID
                                              FROM (SELECT I.ID_CLIENTE_AUC 
                                                    FROM (SELECT DISTINCT(NVL(U.ID_CLIENTE_AUC,0)) AS ID_CLIENTE_AUC
                                                          FROM ' || TABLE_NAME || ' U, ADC_TX_JOBID_SESSION J 
                                                          WHERE U.ID_FLUSSO = J.FLUSSO_ID AND J.VIRTUAL_QUEUE='''|| V_VIRTUAL_QUEUE ||''' AND J.SESSION_ID = ' ||INPUT_ID_SESSION || ') I
                                                    ORDER BY I.ID_CLIENTE_AUC)
                                              )
                                        WHERE ROW_NUM IN ('|| IN_ROWNUM ||')';

                    V_CUR_HDL := DBMS_SQL.OPEN_CURSOR;

                    DBMS_SQL.PARSE(v_cur_hdl, queryContatti, DBMS_SQL.NATIVE);
                    DBMS_SQL.DEFINE_COLUMN(v_cur_hdl, 1, TMP_ROW_NUM);
                    DBMS_SQL.DEFINE_COLUMN(V_CUR_HDL, 2, TMP_ID);

                    V_IGNORE := DBMS_SQL.EXECUTE(V_CUR_HDL);
                    V_REF_CURSOR := DBMS_SQL.TO_REFCURSOR(V_CUR_HDL);

                    COUNTER :=0;

                    LOOP
                      FETCH V_REF_CURSOR
                        INTO TMP_ROW_NUM, TMP_ID;
                    EXIT WHEN V_REF_CURSOR%NOTFOUND;
                      COUNTER := COUNTER + 1;

                      PARALLEL_RECORD.ROW_NUM := TMP_ROW_NUM;
                      PARALLEL_RECORD.ID := TMP_ID;

                      PARALLEL_TABLE(TMP_ROW_NUM) := PARALLEL_RECORD;
                    END LOOP;

                    IF V_REF_CURSOR%isopen then
                      CLOSE V_REF_CURSOR;
                    END IF; 

                    I_QUEUEE := 1;

                    FOR ELEM IN 1 .. ROWNUMS.COUNT LOOP

						IF(MOD(ELEM,2) =0) THEN

							CURRENT_MAX_ID_CLIENTE_AUC := PARALLEL_TABLE(ROWNUMS(ELEM)).ID; 

							NAME_JOB := SUBSTR('ENQ_' || LPAD(TO_CHAR(INPUT_ID_SESSION), 4, '0') || '_' || QUEUES(I_QUEUEE), 1 , 29);
						  --DBMS_OUTPUT.PUT_LINE(NAME_JOB);

							DBMS_SCHEDULER.CREATE_JOB (
							JOB_NAME            =>  $$PLSQL_UNIT_OWNER||'.' || NAME_JOB,
							JOB_TYPE            =>     'STORED_PROCEDURE',
							--JOB_ACTION           =>  $$PLSQL_UNIT_OWNER||'.ADC_PKG_JOBS.ENQUEUE_TT_LOAD_USAGE',
							JOB_ACTION             =>  ENQUEUE_PROCEDURE,
							NUMBER_OF_ARGUMENTS =>  6,
							comments            =>     'Accodamento nella coda ' || QUEUES(I_QUEUEE) );


							/*====== IMPOSTAZIONE PARAMETRI JOB =================================================*/

							/* CONFIGURAZIONE  DEQ_Q01_TT_LOAD_USAGE_01 */

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  argument_position => 1,
							  argument_value => INPUT_ID_SESSION);

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  ARGUMENT_POSITION => 2,
							  argument_value => QUEUES(I_QUEUEE));

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  ARGUMENT_POSITION => 3,
							  argument_value => BAD_RECORD_QUEUE);

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  ARGUMENT_POSITION => 4,
							  argument_value => BLOCK_SIZE);

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  ARGUMENT_POSITION => 5,
							  argument_value => CURRENT_MIN_ID_CLIENTE_AUC);

							DBMS_SCHEDULER.set_job_argument_value(
							  job_name =>  NAME_JOB,
							  ARGUMENT_POSITION => 6,
							  argument_value => CURRENT_MAX_ID_CLIENTE_AUC);

							dbms_scheduler.enable(NAME_JOB);

							LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - ' || NAME_JOB || '  START ON QUEUE: ' || QUEUES(I_QUEUEE), ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION);

							LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, 'INIT_ENQUEUE_CONTATTI ('|| V_VIRTUAL_QUEUE ||') - ' || NAME_JOB || '  MIN_ID_CLIENTE: ' || CURRENT_MIN_ID_CLIENTE_AUC, ADC_PKG_COMMON.INFO_LEVEL, INPUT_ID_SESSION);
