        V_CONTATTI_MESSAGE_BODY_ARRAY   AUC_DG_CONTATTI_MSG_A;
        RETVAL                          PLS_INTEGER;
        V_VIRTUAL_QUEUE                 VARCHAR(255);
        PO_T                            DBMS_AQADM.AQ$_PURGE_OPTIONS_T;
        V_ERR_ENQUEUE_OPTIONS           DBMS_AQ.ENQUEUE_OPTIONS_T;
        V_ERR_MESSAGE_PROPERTIES        DBMS_AQ.MESSAGE_PROPERTIES_T;   
        V_MESSAGE_HANDLE                RAW(16);
        QUEUE_TABLE                     VARCHAR2(255);
        MESSAGE_NUMBER                  NUMBER;

        PRAGMA EXCEPTION_INIT (NO_MESSAGES, -25228);

        IS_DEBUG_ENABLED                BOOLEAN;
        IS_DIAGNOSTIC_ENABLED           BOOLEAN;

        MAXRETRY NUMBER;
        SLEEP_SEC NUMBER;
        j PLS_INTEGER;

        V_CONTATTI_SCARTI_ROW  ADC_BAD_TX_CONTATTI_DG%ROWTYPE;
        V_CONTATTI_TX_TABLE AUC_DG_CONTATTI_MSG_TABLE;

        DIAGNOSTIC_LN VARCHAR2(512):= ADC_PKG_LOAD_AUC_DG.DIAGNOSTIC_LOGGER_NAME;

        TYPE MAP_MESSAGGI_RIMANENTI IS TABLE OF PLS_INTEGER INDEX BY VARCHAR(20 CHAR);
        LISTA_MESSAGGI_RIMANENTI MAP_MESSAGGI_RIMANENTI;

        V_N_MESSAGGI_SCODATI PLS_INTEGER;
        L_KEY VARCHAR(20 CHAR);

        BEGIN

          IS_DIAGNOSTIC_ENABLED   := ADC_PKG_COMMON.IS_LEVEL_ENABLED(ADC_PKG_LOAD_AUC_DG.DIAGNOSTIC_LOGGER_NAME, ADC_PKG_COMMON.INFO_LEVEL);
          IS_DEBUG_ENABLED        := ADC_PKG_COMMON.IS_LEVEL_ENABLED(LOGGER_NAME, ADC_PKG_COMMON.DEBUG_LEVEL);

