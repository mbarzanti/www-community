	FUNCTION createContattiMessage(contattiNode XMLTYPE,idClienteAuc varchar2, TID VARCHAR2 )RETURN AUC_DG_CONTATTI_MSG_TA IS

        l_start       NUMBER;
        l_end         NUMBER;
        LOGRESULT     NUMBER;
        V_TIPO_RIF NUMBER;
        V_RIFERIMENTO VARCHAR(200);

        V_CONTATTI_MESSAGE_BODY AUC_DG_CONTATTI_MSG_TA;
        V_CONTATTI_MESSAGE_BODY_ITEM AUC_DG_CONTATTI_MSG_T;
        V_CONTATTI_MESSAGE_BODY_ITEM_A  AUC_DG_CONTATTI_MSG_TABLE;
        DS_TIMESTAMP TIMESTAMP;
        v_count  number;
        motivo_scarto varchar2(32767);


        BEGIN 


            l_start := DBMS_UTILITY.GET_TIME ;  -- Start Time
            logResult := ADC_PKG_COMMON.LOGGER(LOGGER_NAME, '['|| idClienteAuc ||'] createContattiMessage - BEGIN ', ADC_PKG_COMMON.DEBUG_LEVEL,TID);

            V_CONTATTI_MESSAGE_BODY := AUC_DG_CONTATTI_MSG_TA();
            V_CONTATTI_MESSAGE_BODY_ITEM_A := AUC_DG_CONTATTI_MSG_TABLE();
            v_count := 1;

                WHILE contattiNode.existsNode('/cmf:contatto[' || v_count || ']', ns) = 1 LOOP

                    BEGIN
                        V_TIPO_RIF := NULL;
                        V_RIFERIMENTO := NULL;
                        V_CONTATTI_MESSAGE_BODY_ITEM := AUC_DG_CONTATTI_MSG_T();  

                        IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:idTipoRiferimento', ns)=1) THEN V_TIPO_RIF := contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:idTipoRiferimento/text()', ns).getStringVal(); END IF;
                        IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:riferimento', ns)=1) THEN V_RIFERIMENTO := contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:riferimento/text()', ns).getStringVal();  END IF;
                        IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:dsTimestamp', ns)=1) THEN DS_TIMESTAMP := TO_TIMESTAMP(contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:dsTimestamp/text()', ns).getStringVal(),'yyyy-MM-dd HH24:MI:SS');  END IF;

                        IF(V_TIPO_RIF IS  NULL) THEN                            
                            GESTISCI_SCARTI(id_cliente_auc => idClienteAuc, entità => 'CONTATTO' , id_elemento => NULL, dsTimestamp => DS_TIMESTAMP,  tsLavorazione =>CURRENT_TIMESTAMP, motivoScarto => 'ID_TIPO_RIFERIMENTO NON VALORIZZATO',TID =>TID );
                         ELSIF((V_TIPO_RIF=2 OR V_TIPO_RIF=27 OR V_TIPO_RIF=18 OR V_TIPO_RIF=21) AND NOT (REGEXP_LIKE (V_RIFERIMENTO,'^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,4}$')))  THEN
                            GESTISCI_SCARTI(id_cliente_auc => idClienteAuc, entità => 'CONTATTO' , id_elemento => V_TIPO_RIF, dsTimestamp => DS_TIMESTAMP,  tsLavorazione =>CURRENT_TIMESTAMP, motivoScarto => 'FORMATO EMAIL ERRATO',TID =>TID );
                         ELSE

                            V_CONTATTI_MESSAGE_BODY_ITEM.ID_TIPO_RIFERIMENTO := V_TIPO_RIF;

                            V_CONTATTI_MESSAGE_BODY_ITEM.RIFERIMENTO := V_RIFERIMENTO;
                            V_CONTATTI_MESSAGE_BODY_ITEM.DS_TIMESTAMP := DS_TIMESTAMP;
                            IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:prefisso', ns)=1) THEN V_CONTATTI_MESSAGE_BODY_ITEM.PREFISSO := contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:prefisso/text()', ns).getStringVal();  END IF;
                            IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:idNazione', ns)=1) THEN V_CONTATTI_MESSAGE_BODY_ITEM.ID_PREF_NAZIONE := contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:idNazione/text()', ns).getStringVal();  END IF;
                            IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:dtCessazione', ns)=1) THEN V_CONTATTI_MESSAGE_BODY_ITEM.DT_CESSAZIONE:= TO_TIMESTAMP(contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:dtCessazione/text()', ns).getStringVal(),'YYYYMMDD');  END IF;
                            IF (contattiNode.existsNode('/cmf:contatto[' || v_count || ']/cmf:flagCessazione', ns)=1) THEN V_CONTATTI_MESSAGE_BODY_ITEM.FLG_CANCELLATO:= contattiNode.extract( '/cmf:contatto[' || v_count || ']/cmf:flagCessazione/text()', ns).getStringVal();  END IF;

                            V_CONTATTI_MESSAGE_BODY_ITEM_A.EXTEND();
                            V_CONTATTI_MESSAGE_BODY_ITEM_A(V_CONTATTI_MESSAGE_BODY_ITEM_A.LAST) := V_CONTATTI_MESSAGE_BODY_ITEM;  

                        END IF;

                        v_count := v_count + 1;   

                exception when others then
                    motivo_scarto := sqlerrm;
                    GESTISCI_SCARTI(id_cliente_auc => idClienteAuc, entità => 'CONTATTO' , id_elemento => V_TIPO_RIF, dsTimestamp => DS_TIMESTAMP,  tsLavorazione =>CURRENT_TIMESTAMP, motivoScarto => motivo_scarto ,TID =>TID );
                    v_count :=  v_count + 1;

                end;
                END LOOP;

            V_CONTATTI_MESSAGE_BODY.RETRY_COUNT := 0;
            V_CONTATTI_MESSAGE_BODY.ID_CLIENTE_AUC := idClienteAuc;
            V_CONTATTI_MESSAGE_BODY.CONTATTI_TX_TABLE := V_CONTATTI_MESSAGE_BODY_ITEM_A;

            l_end := DBMS_UTILITY.GET_TIME;

            LOGRESULT := ADC_PKG_COMMON.LOGGER(LOGGER_NAME,  '['|| idClienteAuc ||'] createContattiMessage - END (elapsed:'|| (l_end - l_start)/100 ||' s)', ADC_PKG_COMMON.DEBUG_LEVEL, TID);  

            RETURN V_CONTATTI_MESSAGE_BODY;
    END;

