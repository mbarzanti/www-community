                    BEGIN                                                                                            
						OPEN SESSION_ENQUEUERS_CUR;
						LOOP 
                              FETCH SESSION_ENQUEUERS_CUR INTO ACTIVE_ENQUEUER_NUMBER;
                              EXIT WHEN SESSION_ENQUEUERS_CUR%NOTFOUND;
                              UPDATE ADC_TX_JOBID_SESSION SET ACTIVE_ENQUEUER = 0 
